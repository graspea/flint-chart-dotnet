import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { emitEntries } from '../src/emit/entries.ts';
import { emptyOverrides } from '../src/overrides.ts';
import { syntheticIr } from './support/synthetic-ir.ts';

describe('emit/entries', () => {
  // source: design §4.2 entry point (one quadruple per template: rows + RowOptions with RequiresUnreferencedCode and
  // RequiresDynamicCode, rows + JsonTypeInfo, ChartData, and the [Obsolete(error: true)] string overload), spike (a)
  // change 1 (the string overload wins overload resolution and gives CS0619) and review R1-1 (the JsonTypeInfo overload
  // writes values as the metadata does)
  it('emits the four Chart entries of each chart type', () => {
    const result = emitEntries(syntheticIr(), emptyOverrides());
    assert.deepEqual(result.files.map((f) => f.path), ['Entries/Chart.Line.g.cs']);
    assert.equal(
      result.files[0].content,
      `// <auto-generated/> flint-chart 0.5.1
#nullable enable

using System.Diagnostics.CodeAnalysis;
using System.Text.Json.Serialization.Metadata;
using Graspea.Flint.Serialization;

namespace Graspea.Flint;

public static partial class Chart
{
    /// <summary>Starts a <c>Line Chart</c> document from rows written by reflection (camelCase keys by default).</summary>
    /// <typeparam name="TRow">The row type.</typeparam>
    /// <param name="rows">The rows; written to JSON now.</param>
    /// <param name="options">Key naming; <c>RowOptions.Default</c> when omitted. A literal <c>null</c> here does not compile (ambiguous with the <c>JsonTypeInfo</c> overload); omit the argument.</param>
    /// <returns>The builder.</returns>
    [RequiresUnreferencedCode(RowMaterializer.ReflectionMessage)]
    [RequiresDynamicCode(RowMaterializer.ReflectionMessage)]
    public static LineChartBuilder<TRow> Line<TRow>(IEnumerable<TRow> rows, RowOptions? options = null) => new(ChartRows.Of(rows, options));

    /// <summary>Starts a <c>Line Chart</c> document from rows written through source-generated or custom metadata (trimming- and AOT-safe).</summary>
    /// <typeparam name="TRow">The row type.</typeparam>
    /// <param name="rows">The rows; written to JSON now.</param>
    /// <param name="typeInfo">A <c>JsonTypeInfo&lt;TRow&gt;</c>, typically from a source-generated <c>JsonSerializerContext</c>, whose null members are written rather than omitted (trimming- and AOT-safe).</param>
    /// <returns>The builder.</returns>
    /// <remarks>Values are written exactly as this metadata writes them, unlike the reflection overload: enums as numbers unless the context sets <c>UseStringEnumConverter = true</c>, and a <c>NaN</c> or infinite <c>double</c> throws unless the row maps it to <c>null</c>. Recommended: <c>[JsonSourceGenerationOptions(UseStringEnumConverter = true, DefaultIgnoreCondition = JsonIgnoreCondition.Never)]</c>.</remarks>
    public static LineChartBuilder<TRow> Line<TRow>(IEnumerable<TRow> rows, JsonTypeInfo<TRow> typeInfo) => new(ChartRows.Of(rows, typeInfo));

    /// <summary>Starts a <c>Line Chart</c> document over data that is already built (JSON rows or a URL); bind fields by name.</summary>
    /// <param name="data">The data.</param>
    /// <returns>The builder.</returns>
    public static LineChartBuilder<object> Line(ChartData data) => new(ChartRows.Of(data));

    /// <summary>Not row data: a string is <c>IEnumerable&lt;char&gt;</c>. Use <c>Chart.Line(ChartData.FromUrl(url))</c>.</summary>
    /// <param name="url">The URL.</param>
    /// <returns>Never returns.</returns>
    [Obsolete("A string is IEnumerable<char>; use Chart.Line(ChartData.FromUrl(url)).", error: true)]
    public static LineChartBuilder<object> Line(string url) => throw ChartRows.UrlIsNotRows();
}
`,
    );
  });

  // source: design §8.2 (the entries are generated members of the hand-written Chart class; the generator owns exactly
  // their API lines)
  it('lists the public API of the entries and owns the entry members of Chart', () => {
    const result = emitEntries(syntheticIr(), emptyOverrides());
    assert.deepEqual(result.apiLines, [
      'static Graspea.Flint.Chart.Line<TRow>(System.Collections.Generic.IEnumerable<TRow>! rows, Graspea.Flint.RowOptions? options = null) -> Graspea.Flint.LineChartBuilder<TRow>!',
      'static Graspea.Flint.Chart.Line<TRow>(System.Collections.Generic.IEnumerable<TRow>! rows, System.Text.Json.Serialization.Metadata.JsonTypeInfo<TRow>! typeInfo) -> Graspea.Flint.LineChartBuilder<TRow>!',
      'static Graspea.Flint.Chart.Line(Graspea.Flint.ChartData! data) -> Graspea.Flint.LineChartBuilder<object!>!',
      'static Graspea.Flint.Chart.Line(string! url) -> Graspea.Flint.LineChartBuilder<object!>!',
    ]);
    assert.deepEqual(result.ownedMembers, ['Graspea.Flint.Chart.Line']);
  });

  // source: design §4.2 (Chart.Of is the hand-written entry; an entry of the same name would collide with it)
  it('fails on an entry name taken by the hand-written Chart members', () => {
    const ir = syntheticIr();
    ir.catalog.chartTypes[0].name = 'Of Chart';
    assert.throws(() => emitEntries(ir, emptyOverrides()), /"Of".*catalog\.chartTypes\[Of Chart\].*Chart\.Of/);
  });
});
