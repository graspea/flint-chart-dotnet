import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { emitCSharpNames } from '../src/emit/csharp-names.ts';
import { emptyOverrides } from '../src/overrides.ts';
import type { Ir } from '../src/ir.ts';
import { syntheticIr } from './support/synthetic-ir.ts';

/** The synthetic IR with the literal unions the constants need and a two-member AssembleOptions. */
function irWithTypes(): Ir {
  const ir = syntheticIr();
  ir.types = {
    AssembleOptions: {
      kind: 'object',
      props: [
        { name: 'addTooltips', optional: true, type: { kind: 'boolean' } },
        { name: 'targetBandAR', optional: true, type: { kind: 'number' } },
      ],
    },
    ChartEncoding: {
      kind: 'object',
      props: [
        { name: 'aggregate', optional: true, type: { kind: 'literalUnion', values: ['count'] } },
        { name: 'sortOrder', optional: true, type: { kind: 'literalUnion', values: ['ascending'] } },
        { name: 'type', optional: true, type: { kind: 'literalUnion', values: ['temporal'] } },
      ],
    },
    ContinuousMarkCrossSection: {
      kind: 'union',
      members: [{ kind: 'number' }, { kind: 'object', props: [{ name: 'seriesCountAxis', optional: true, type: { kind: 'literalUnion', values: ['auto'] } }] }],
    },
  };
  return ir;
}

describe('emit/csharp-names', () => {
  // source: design §12.7 (NameTables.g.cs: chart type -> constant and entry; per template channel -> facade method,
  // property key -> method, kind and, for an enum, the type and the wire value -> member map; semantic type -> constant
  // with its first visEncodings entry; presets; literal structs; AssembleOptions and Theming wire name -> C# property and
  // type), names from the shared fluent model and the constants emitter
  it('writes the name tables of the synthetic IR', () => {
    const files = emitCSharpNames(irWithTypes(), emptyOverrides());
    assert.deepEqual(files.map((f) => f.path), ['NameTables.g.cs', 'Catalog.g.cs']);
    assert.equal(
      files[0].content,
      `// <auto-generated/> flint-chart 0.5.1
#nullable enable

namespace Graspea.Flint.CSharp;

internal static partial class NameTables
{
    internal static readonly TemplateNames[] Templates =
    [
        new("Line Chart", "LineChart", "Line",
            [new("x", "X"), new("y", "Y"), new("color", "Color")],
            [
                new("interpolate", "Interpolate", PropertyKind.Enum, "LineChartInterpolate", [new(WireKind.String, "monotone", "Monotone")]),
                new("showPoints", "ShowPoints", PropertyKind.Bool, null, []),
                new("strokeWidth", "StrokeWidth", PropertyKind.Double, null, []),
            ]),
    ];

    internal static readonly ConstantName[] Channels =
    [
        new("x", "X"),
        new("y", "Y"),
        new("color", "Color"),
    ];

    internal static readonly SemanticTypeName[] SemanticTypes =
    [
        new("YearMonth", "YearMonth", "temporal"),
    ];

    internal static readonly ConstantName[] ThemePresets =
    [
        new("powerbi-light", "PowerbiLight"),
    ];

    internal static readonly ConstantName[] EncodingTypes =
    [
        new("temporal", "Temporal"),
    ];

    internal static readonly ConstantName[] Aggregates =
    [
        new("count", "Count"),
    ];

    internal static readonly ConstantName[] SortOrders =
    [
        new("ascending", "Ascending"),
    ];

    internal static readonly ConstantName[] SeriesCountAxes =
    [
        new("auto", "Auto"),
    ];

    internal static readonly ClassNames[] Classes =
    [
        new("Graspea.Flint.AssembleOptions",
        [
            new("addTooltips", "AddTooltips", "bool"),
            new("targetBandAR", "TargetBandAr", "double"),
        ]),
    ];
}
`,
    );
  });

  // source: design §12.7 (Catalog.g.cs: what the catalog checks need: templates per backend with channels and properties
  // (kind, options, ranges), backendsApplyingTheme and host-state keys) and the library's tables emitter (src/emit/tables.ts:
  // discrete options as the JSON text of the value, null for an omitted option, with their labels)
  it('writes the catalog tables of the synthetic IR', () => {
    const files = emitCSharpNames(irWithTypes(), emptyOverrides());
    assert.equal(
      files[1].content,
      `// <auto-generated/> flint-chart 0.5.1
#nullable enable

namespace Graspea.Flint.CSharp;

internal static partial class Catalog
{
    internal static readonly string[] Backends = ["vegalite", "excel"];

    internal static readonly string[] BackendsApplyingTheme = ["vegalite"];

    internal static readonly string[] HostStateKeys = ["sort"];

    internal static readonly ChartTypeRow[] ChartTypes =
    [
        new("Line Chart",
        [
            new("vegalite", ["x", "y", "color"],
            [
                new("interpolate", CatalogPropertyKind.Discrete, [null, "\\"monotone\\""], ["Default", "Monotone"], null, null),
                new("showPoints", CatalogPropertyKind.Binary, null, null, null, null),
                new("strokeWidth", CatalogPropertyKind.Continuous, null, null, 0.5, 5),
            ]),
            new("excel", ["x", "y"], []),
        ]),
    ];
}
`,
    );
  });

  // source: design §12.7 (renames from overrides.json are applied, because the fluent model applies them) and
  // docs/generator.md "renames"
  it('applies the overrides.json renames to constants and enum members', () => {
    const overrides = emptyOverrides();
    overrides.renames['catalog.themePresets[powerbi-light]'] = 'PowerBiLight';
    overrides.renames['Line Chart/enum/interpolate/monotone'] = 'Smooth';
    const content = emitCSharpNames(irWithTypes(), overrides)[0].content;
    assert.match(content, /new\("powerbi-light", "PowerBiLight"\)/);
    assert.match(content, /\[new\(WireKind\.String, "monotone", "Smooth"\)\]/);
  });

  // source: generator/src/emit/enums.ts wireValue (a member of an array option writes its label) and design §12.4.1
  // (the reverse table is keyed by the JSON value the member writes)
  it('keys an array option by the label its member writes, and numbers and booleans by their JSON text', () => {
    const ir = irWithTypes();
    ir.catalog.chartTypes[0].backends.vegalite.properties.push({
      key: 'center',
      label: 'Center',
      type: 'discrete',
      options: [
        { label: 'Europe [10, 50]', value: [10, 50] },
        { label: 'Four', value: 4 },
        { label: 'Yes', value: true },
      ],
    });
    const content = emitCSharpNames(ir, emptyOverrides())[0].content;
    assert.match(
      content,
      /new\("center", "Center", PropertyKind\.Enum, "LineChartCenter", \[new\(WireKind\.String, "Europe \[10, 50\]", "Europe"\), new\(WireKind\.Number, "4", "Four"\), new\(WireKind\.Boolean, "true", "Yes"\)\]\),/,
    );
  });
});
