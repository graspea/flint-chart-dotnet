import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { declaredPublicTypes, unshippedText } from '../src/emit/public-api.ts';
import { emptyResult } from '../src/emit/common.ts';

describe('emit/public-api', () => {
  const generated = () => {
    const r = emptyResult();
    r.apiLines = [
      'Graspea.Flint.AssembleOptions',
      'Graspea.Flint.AssembleOptions.AddTooltips.get -> bool?',
      'static readonly Graspea.Flint.ChartType.LineChart -> Graspea.Flint.ChartType',
      'const Graspea.Flint.FlintUpstream.Version = "0.5.1" -> string!',
    ];
    r.ownedTypes = ['Graspea.Flint.AssembleOptions', 'Graspea.Flint.FlintUpstream'];
    r.ownedConstantStructs = ['Graspea.Flint.ChartType'];
    return r;
  };

  // source: design §7.4 (public-api: writes only generated symbols not yet shipped; both files start with #nullable enable)
  it('adds the generated symbols that are not shipped, sorted ordinally, after #nullable enable', () => {
    const shipped = '#nullable enable\nGraspea.Flint.AssembleOptions\n';
    assert.equal(
      unshippedText(shipped, '#nullable enable\n', generated()),
      '#nullable enable\n' +
        'Graspea.Flint.AssembleOptions.AddTooltips.get -> bool?\n' +
        'const Graspea.Flint.FlintUpstream.Version = "0.5.1" -> string!\n' +
        'static readonly Graspea.Flint.ChartType.LineChart -> Graspea.Flint.ChartType\n',
    );
  });

  // source: design §3 (PublicAPI files list hand-written and generated symbols; the generator owns only its own lines)
  it('keeps hand-written lines and drops generated lines that vanished', () => {
    const unshipped =
      '#nullable enable\n' +
      'Graspea.Flint.ChartType.Name.get -> string!\n' +
      'static readonly Graspea.Flint.ChartType.GoneChart -> Graspea.Flint.ChartType\n' +
      'Graspea.Flint.AssembleOptions.Gone.get -> double?\n' +
      '~override Graspea.Flint.ChartType.Equals(object obj) -> bool\n';
    const text = unshippedText('#nullable enable\n', unshipped, generated());
    assert.ok(text.includes('Graspea.Flint.ChartType.Name.get -> string!\n'));
    assert.ok(text.includes('~override Graspea.Flint.ChartType.Equals(object obj) -> bool\n'));
    assert.ok(!text.includes('GoneChart'));
    assert.ok(!text.includes('AssembleOptions.Gone'));
  });

  // source: design §8.2 (the Chart.<Name> entries are generated members of the hand-written Chart class): the generator owns
  // every overload of an entry it emits, and the hand-written Chart.Of lines stay
  it('owns the overloads of generated members of hand-written types', () => {
    const result = emptyResult();
    result.apiLines = ['static Graspea.Flint.Chart.Line(Graspea.Flint.ChartData! data) -> Graspea.Flint.LineChartBuilder<object!>!'];
    result.ownedMembers = ['Graspea.Flint.Chart.Line', 'Graspea.Flint.Chart.Gone'];
    const unshipped =
      '#nullable enable\n' +
      'static Graspea.Flint.Chart.Gone<TRow>(System.Collections.Generic.IEnumerable<TRow>! rows) -> Graspea.Flint.GoneBuilder<TRow>!\n' +
      'static Graspea.Flint.Chart.Line(string! url) -> Graspea.Flint.LineChartBuilder<object!>!\n' +
      'static Graspea.Flint.Chart.Of(Graspea.Flint.ChartType chartType, Graspea.Flint.ChartData! data) -> Graspea.Flint.GenericChartBuilder<object!>!\n' +
      'static Graspea.Flint.Chart.LineX(string! url) -> Graspea.Flint.LineChartBuilder<object!>!\n';
    assert.equal(
      unshippedText('#nullable enable\n', unshipped, result),
      '#nullable enable\n' +
        'static Graspea.Flint.Chart.Line(Graspea.Flint.ChartData! data) -> Graspea.Flint.LineChartBuilder<object!>!\n' +
        'static Graspea.Flint.Chart.LineX(string! url) -> Graspea.Flint.LineChartBuilder<object!>!\n' +
        'static Graspea.Flint.Chart.Of(Graspea.Flint.ChartType chartType, Graspea.Flint.ChartData! data) -> Graspea.Flint.GenericChartBuilder<object!>!\n',
    );
  });

  // source: design §7.2 (each step is idempotent)
  it('is idempotent', () => {
    const once = unshippedText('#nullable enable\n', '#nullable enable\nGraspea.Flint.Channel\n', generated());
    assert.equal(unshippedText('#nullable enable\n', once, generated()), once);
  });

  // source: design §7.4 (the generator owns its generated lines): when a generated file is removed (an enum renamed through
  // overrides.json, a template retired upstream), the public types it declared are owned too, so their lines leave
  // PublicAPI.Unshipped.txt instead of staying behind as RS0017 errors
  it('reads the public types a generated file declares', () => {
    const content =
      '// <auto-generated/> flint-chart 0.5.1\n#nullable enable\n\nnamespace Graspea.Flint;\n\n' +
      '/// <summary>x</summary>\npublic enum RegressionRegressionMethod\n{\n    Default = 0,\n}\n\n' +
      'internal static class RegressionRegressionMethodValues\n{\n}\n\n' +
      'public sealed partial class RegressionBuilder<TRow> : ChartBuilder<RegressionBuilder<TRow>, TRow>\n{\n}\n';
    assert.deepEqual(declaredPublicTypes(content), ['Graspea.Flint.RegressionRegressionMethod', 'Graspea.Flint.RegressionBuilder<TRow>']);
    assert.deepEqual(declaredPublicTypes('namespace Graspea.Flint;\n\npublic static partial class Chart\n{\n}\n'), []);
  });
});
