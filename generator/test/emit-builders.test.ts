import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { emitBuilders } from '../src/emit/builders.ts';
import { emptyOverrides, type Overrides } from '../src/overrides.ts';
import type { Ir } from '../src/ir.ts';
import { syntheticIr } from './support/synthetic-ir.ts';

const overrides = (change: Partial<Overrides> = {}): Overrides => ({ ...emptyOverrides(), ...change });

/** Scatter Plot: an `opacity` channel and an `opacity` property (design §4.2 collision rule). */
function scatterIr(): Ir {
  const ir = syntheticIr();
  ir.catalog.channels.push('opacity');
  ir.catalog.chartTypes = [
    {
      name: 'Scatter Plot',
      backends: {
        vegalite: {
          channels: ['x', 'opacity'],
          properties: [{ key: 'opacity', label: 'Opacity', type: 'continuous', min: 0, max: 1 }],
        },
        excel: { channels: ['x'], properties: [{ key: 'opacity', label: 'Opacity', type: 'continuous', min: 0.1, max: 1, step: 0.1 }] },
      },
    },
  ];
  return ir;
}

/** Radar Chart: `filled` is binary on vegalite and discrete on excel (the 0.5.1 kind mismatch, design §7.4). */
function radarIr(): Ir {
  const ir = syntheticIr();
  ir.catalog.chartTypes = [
    {
      name: 'Radar Chart',
      backends: {
        vegalite: { channels: ['x'], properties: [{ key: 'filled', label: 'Fill', type: 'binary' }] },
        excel: {
          channels: ['x'],
          properties: [
            {
              key: 'filled',
              label: 'Fill',
              type: 'discrete',
              options: [
                { label: 'Filled (default)', value: true },
                { label: 'Outline only', value: false },
              ],
            },
          ],
        },
      },
    },
  ];
  return ir;
}

describe('emit/builders', () => {
  // source: design §4.2 generated facades (sealed partial {Name}Builder<TRow> over the CRTP core; per channel the string,
  // Expression and ChartEncoding overloads; discrete -> per-template enum, binary -> bool, continuous -> double; every
  // method a one-liner over a core method), §7.4/§7.5 (XML docs from the catalog: label and backends) and design 05 XML
  // doc rules (builders get an <example><code> with a complete snippet: the entry and the first two channels)
  it('emits one sealed partial builder per chart type', () => {
    const result = emitBuilders(syntheticIr(), overrides());
    assert.deepEqual(result.files.map((f) => f.path), ['Builders/LineChartBuilder.g.cs']);
    assert.equal(
      result.files[0].content,
      `// <auto-generated/> flint-chart 0.5.1
#nullable enable

using System.Linq.Expressions;
using System.Text.Json.Nodes;

namespace Graspea.Flint;

/// <summary>Builds a <c>Line Chart</c> document; backends: vegalite, excel. Start with <c>Chart.Line(rows)</c>.</summary>
/// <typeparam name="TRow">The row type.</typeparam>
/// <example>
/// <code>
/// var rows = new[] { new { X = 1.0, Y = 3.0 }, new { X = 2.0, Y = 5.0 } };
/// string json = Chart.Line(rows).X(r =&gt; r.X).Y(r =&gt; r.Y).ToJson();
/// </code>
/// </example>
public sealed partial class LineChartBuilder<TRow> : ChartBuilder<LineChartBuilder<TRow>, TRow>
{
    internal LineChartBuilder(ChartRows<TRow> rows)
        : base(ChartType.LineChart, rows.Data, rows.TypeInfo)
    {
    }

    /// <summary>Binds the <c>x</c> channel to a field. Declared by every backend of the template.</summary>
    /// <param name="field">The field: a key of the rows, used verbatim.</param>
    /// <param name="semanticType">When set, also annotates the field in <c>semantic_types</c>.</param>
    /// <returns>This builder.</returns>
    public LineChartBuilder<TRow> X(string field, SemanticType? semanticType = null) => Encode(Channel.X, field, semanticType);

    /// <summary>Binds the <c>x</c> channel to the field a row member is written as. Declared by every backend of the template.</summary>
    /// <param name="selector">A property or field of the row, such as <c>r =&gt; r.Month</c>.</param>
    /// <param name="semanticType">When set, also annotates the field in <c>semantic_types</c>.</param>
    /// <returns>This builder.</returns>
    public LineChartBuilder<TRow> X(Expression<Func<TRow, object?>> selector, SemanticType? semanticType = null) => Encode(Channel.X, selector, semanticType);

    /// <summary>Binds the <c>x</c> channel to an encoding with any of its members. Declared by every backend of the template.</summary>
    /// <param name="encoding">The encoding; the builder keeps a copy.</param>
    /// <returns>This builder.</returns>
    public LineChartBuilder<TRow> X(ChartEncoding encoding) => Encode(Channel.X, encoding);

    /// <summary>Binds the <c>y</c> channel to a field. Declared by every backend of the template.</summary>
    /// <param name="field">The field: a key of the rows, used verbatim.</param>
    /// <param name="semanticType">When set, also annotates the field in <c>semantic_types</c>.</param>
    /// <returns>This builder.</returns>
    public LineChartBuilder<TRow> Y(string field, SemanticType? semanticType = null) => Encode(Channel.Y, field, semanticType);

    /// <summary>Binds the <c>y</c> channel to the field a row member is written as. Declared by every backend of the template.</summary>
    /// <param name="selector">A property or field of the row, such as <c>r =&gt; r.Month</c>.</param>
    /// <param name="semanticType">When set, also annotates the field in <c>semantic_types</c>.</param>
    /// <returns>This builder.</returns>
    public LineChartBuilder<TRow> Y(Expression<Func<TRow, object?>> selector, SemanticType? semanticType = null) => Encode(Channel.Y, selector, semanticType);

    /// <summary>Binds the <c>y</c> channel to an encoding with any of its members. Declared by every backend of the template.</summary>
    /// <param name="encoding">The encoding; the builder keeps a copy.</param>
    /// <returns>This builder.</returns>
    public LineChartBuilder<TRow> Y(ChartEncoding encoding) => Encode(Channel.Y, encoding);

    /// <summary>Binds the <c>color</c> channel to a field. Declared by vegalite; not by excel, where <c>Validate(backend)</c> reports <c>unsupported_channel</c>.</summary>
    /// <param name="field">The field: a key of the rows, used verbatim.</param>
    /// <param name="semanticType">When set, also annotates the field in <c>semantic_types</c>.</param>
    /// <returns>This builder.</returns>
    public LineChartBuilder<TRow> Color(string field, SemanticType? semanticType = null) => Encode(Channel.Color, field, semanticType);

    /// <summary>Binds the <c>color</c> channel to the field a row member is written as. Declared by vegalite; not by excel, where <c>Validate(backend)</c> reports <c>unsupported_channel</c>.</summary>
    /// <param name="selector">A property or field of the row, such as <c>r =&gt; r.Month</c>.</param>
    /// <param name="semanticType">When set, also annotates the field in <c>semantic_types</c>.</param>
    /// <returns>This builder.</returns>
    public LineChartBuilder<TRow> Color(Expression<Func<TRow, object?>> selector, SemanticType? semanticType = null) => Encode(Channel.Color, selector, semanticType);

    /// <summary>Binds the <c>color</c> channel to an encoding with any of its members. Declared by vegalite; not by excel, where <c>Validate(backend)</c> reports <c>unsupported_channel</c>.</summary>
    /// <param name="encoding">The encoding; the builder keeps a copy.</param>
    /// <returns>This builder.</returns>
    public LineChartBuilder<TRow> Color(ChartEncoding encoding) => Encode(Channel.Color, encoding);

    /// <summary>Sets the <c>interpolate</c> chart property ("Curve"). Declared by vegalite; not by excel, where <c>Validate(backend)</c> reports <c>unknown_chart_property</c>.</summary>
    /// <param name="value">The value; <c>Default</c> omits the key.</param>
    /// <returns>This builder.</returns>
    public LineChartBuilder<TRow> Interpolate(LineChartInterpolate value) => Property("interpolate", LineChartInterpolateValues.ToJson(value));

    /// <summary>Sets the <c>showPoints</c> chart property ("Points"). Declared by vegalite; not by excel, where <c>Validate(backend)</c> reports <c>unknown_chart_property</c>.</summary>
    /// <param name="value">The value.</param>
    /// <returns>This builder.</returns>
    public LineChartBuilder<TRow> ShowPoints(bool value) => Property("showPoints", value);

    /// <summary>Sets the <c>strokeWidth</c> chart property ("Width"). Declared by vegalite; not by excel, where <c>Validate(backend)</c> reports <c>unknown_chart_property</c>.</summary>
    /// <param name="value">The value; 0.5 to 5, step 0.5.</param>
    /// <returns>This builder.</returns>
    public LineChartBuilder<TRow> StrokeWidth(double value) => Property("strokeWidth", value);
}
`,
    );
  });

  // source: design §8.2 and §10.3 (every generated symbol is in the PublicAPI files; the facade emitter emits the fixed
  // overload set and nothing else)
  it('lists the public API of every builder and owns the builder types', () => {
    const result = emitBuilders(syntheticIr(), overrides());
    const self = 'Graspea.Flint.LineChartBuilder<TRow>!';
    assert.deepEqual(result.ownedTypes, ['Graspea.Flint.LineChartBuilder<TRow>']);
    assert.deepEqual(result.apiLines, [
      'Graspea.Flint.LineChartBuilder<TRow>',
      `Graspea.Flint.LineChartBuilder<TRow>.X(string! field, Graspea.Flint.SemanticType? semanticType = null) -> ${self}`,
      `Graspea.Flint.LineChartBuilder<TRow>.X(System.Linq.Expressions.Expression<System.Func<TRow, object?>!>! selector, Graspea.Flint.SemanticType? semanticType = null) -> ${self}`,
      `Graspea.Flint.LineChartBuilder<TRow>.X(Graspea.Flint.ChartEncoding! encoding) -> ${self}`,
      `Graspea.Flint.LineChartBuilder<TRow>.Y(string! field, Graspea.Flint.SemanticType? semanticType = null) -> ${self}`,
      `Graspea.Flint.LineChartBuilder<TRow>.Y(System.Linq.Expressions.Expression<System.Func<TRow, object?>!>! selector, Graspea.Flint.SemanticType? semanticType = null) -> ${self}`,
      `Graspea.Flint.LineChartBuilder<TRow>.Y(Graspea.Flint.ChartEncoding! encoding) -> ${self}`,
      `Graspea.Flint.LineChartBuilder<TRow>.Color(string! field, Graspea.Flint.SemanticType? semanticType = null) -> ${self}`,
      `Graspea.Flint.LineChartBuilder<TRow>.Color(System.Linq.Expressions.Expression<System.Func<TRow, object?>!>! selector, Graspea.Flint.SemanticType? semanticType = null) -> ${self}`,
      `Graspea.Flint.LineChartBuilder<TRow>.Color(Graspea.Flint.ChartEncoding! encoding) -> ${self}`,
      `Graspea.Flint.LineChartBuilder<TRow>.Interpolate(Graspea.Flint.LineChartInterpolate value) -> ${self}`,
      `Graspea.Flint.LineChartBuilder<TRow>.ShowPoints(bool value) -> ${self}`,
      `Graspea.Flint.LineChartBuilder<TRow>.StrokeWidth(double value) -> ${self}`,
    ]);
  });

  // source: design §4.2 collision rule (channel and property share a key: the channel keeps Opacity, the property becomes
  // OpacityValue) and §7.5 (continuous ranges per backend in the docs)
  it('names a property that shares a channel key with the Value suffix', () => {
    const content = emitBuilders(scatterIr(), overrides()).files[0].content;
    assert.ok(content.includes('    public ScatterPlotBuilder<TRow> Opacity(string field, SemanticType? semanticType = null) => Encode(Channel.Opacity, field, semanticType);\n'));
    assert.ok(content.includes('    /// <param name="value">The value; vegalite: 0 to 1; excel: 0.1 to 1, step 0.1.</param>\n'));
    assert.ok(content.includes('    public ScatterPlotBuilder<TRow> OpacityValue(double value) => Property("opacity", value);\n'));
  });

  // source: design §7.4 property kind rule (a key whose kind differs across the backends of one template fails generation
  // with both IR paths unless overrides.json maps it; the 0.5.1 override maps Radar Chart filled to JsonNode)
  it('fails on a kind mismatch without an override and emits a JsonNode setter with one', () => {
    assert.throws(
      () => emitBuilders(radarIr(), overrides()),
      (e: Error) =>
        e.message.includes('catalog.chartTypes[Radar Chart].backends.vegalite.properties[filled]') &&
        e.message.includes('catalog.chartTypes[Radar Chart].backends.excel.properties[filled]'),
    );
    const content = emitBuilders(radarIr(), overrides({ unions: { 'Radar Chart/property/filled': 'JsonNode' } })).files[0].content;
    assert.ok(
      content.includes(
        '    /// <summary>Sets the <c>filled</c> chart property ("Fill"). Declared by every backend of the template. ' +
          'Its kind differs across backends (vegalite: binary; excel: discrete), so the value is raw JSON.</summary>\n' +
          '    /// <param name="value">The value; null removes the key.</param>\n' +
          '    /// <returns>This builder.</returns>\n' +
          '    public RadarChartBuilder<TRow> Filled(JsonNode? value) => Property("filled", value);\n',
      ),
    );
  });

  // source: design §7.6 rule 6 (the fix for a collision is renames["<Template>/property/<key>"])
  it('applies template renames from overrides.json', () => {
    const content = emitBuilders(syntheticIr(), overrides({ renames: { 'Line Chart/property/showPoints': 'Dots' } })).files[0].content;
    assert.ok(content.includes('    public LineChartBuilder<TRow> Dots(bool value) => Property("showPoints", value);\n'));
  });

  // source: docs/validation-codes.md unknown_chart_property (an undeclared key is reported, except the host-state keys of
  // catalog.hostStateKeys, which upstream reads even where undeclared)
  it('does not promise unknown_chart_property for a host-state key', () => {
    const ir = syntheticIr();
    ir.catalog.chartTypes[0].backends.vegalite.properties.push({ key: 'sort', label: 'Sort', type: 'binary' });
    const content = emitBuilders(ir, overrides()).files[0].content;
    assert.ok(content.includes('/// <summary>Sets the <c>sort</c> chart property ("Sort"). Declared by vegalite; not by excel. It is a host-state key, read even where undeclared, so <c>Validate(backend)</c> does not report it.</summary>\n'));
  });

  // source: design §7.6 rules 3 and 6 (renames["<Template>/enum/<key>"] names the enum; the builder method takes it)
  it('takes the renamed enum in the property method', () => {
    const content = emitBuilders(syntheticIr(), overrides({ renames: { 'Line Chart/enum/interpolate': 'Curve' } })).files[0].content;
    assert.ok(content.includes('    public LineChartBuilder<TRow> Interpolate(Curve value) => Property("interpolate", CurveValues.ToJson(value));\n'));
  });

  // source: design §7.6 rule 6 (a remaining collision fails generation with the IR paths): two templates whose builder or
  // enum names coincide cannot both be emitted (a discrete property `builder` on Line Chart would be LineChartBuilder)
  it('fails when two generated type names collide', () => {
    const ir = syntheticIr();
    ir.catalog.chartTypes[0].backends.vegalite.properties.unshift({ key: 'builder', label: 'B', type: 'discrete', options: [{ label: 'A', value: 'a' }] });
    assert.throws(
      () => emitBuilders(ir, overrides()),
      (e: Error) => e.message.includes('"LineChartBuilder"') && e.message.includes('catalog.chartTypes[Line Chart]') && e.message.includes('catalog.chartTypes[Line Chart].properties[builder]'),
    );
  });

  // source: design 05 XML doc rules (a complete snippet per builder; facets are skipped, a single-channel template binds one)
  it('writes an example over the first two non-facet channels', () => {
    const ir = syntheticIr();
    ir.catalog.chartTypes[0].backends.vegalite!.channels = ['column', 'size'];
    ir.catalog.chartTypes[0].backends.excel!.channels = ['size'];
    const content = emitBuilders(ir, overrides()).files[0].content;
    assert.match(content, /\/\/\/ var rows = new\[\] \{ new \{ Size = 1\.0 \}, new \{ Size = 2\.0 \} \};\n\/\/\/ string json = Chart\.Line\(rows\)\.Size\(r =&gt; r\.Size\)\.ToJson\(\);\n/);
  });
});
