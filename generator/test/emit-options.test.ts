import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { emitOptions } from '../src/emit/options.ts';
import { checkPropertyKinds } from '../src/emit/property-kinds.ts';
import { emptyOverrides, parseOverrides, type Overrides } from '../src/overrides.ts';
import type { Ir, IrNamedType } from '../src/ir.ts';
import { syntheticIr } from './support/synthetic-ir.ts';

const crossSection: IrNamedType = {
  kind: 'union',
  members: [
    { kind: 'number' },
    { kind: 'object', props: [{ name: 'x', optional: false, type: { kind: 'number' } }] },
  ],
};

function irWith(types: Record<string, IrNamedType>): Ir {
  const ir = syntheticIr();
  ir.types = types;
  return ir;
}

function overrides(partial: Partial<Overrides>): Overrides {
  return { ...emptyOverrides(), ...partial };
}

/** The content of one emitted file, by its path under Generated/. */
const fileContent = (result: { files: { path: string; content: string }[] }, path: string): string => {
  const file = result.files.find((f) => f.path === path);
  assert.ok(file, `${path} was not emitted`);
  return file.content;
};

const options = (props: Extract<IrNamedType, { kind: 'object' }>['props'], doc?: string): IrNamedType =>
  doc ? { kind: 'object', doc, props } : { kind: 'object', props };

describe('emit/options', () => {
  // source: design §7.4 (unions fail generation with the IR path unless overrides.json maps them) and §10.4 test 5a
  it('fails on continuousMarkCrossSection without an override, naming the IR path', () => {
    const ir = irWith({
      AssembleOptions: options([{ name: 'continuousMarkCrossSection', optional: true, type: crossSection }]),
    });
    assert.throws(() => emitOptions(ir, emptyOverrides()), /AssembleOptions\.continuousMarkCrossSection/);
  });

  // source: design §7.4 type mapping and §4.1 member shape (JsonPropertyName, WhenWritingNull, Strict number handling,
  // closed-generic VerbatimKeyDictionaryConverter<T>, trailing Dictionary<string, JsonElement>? Extensions) and §10.4 test 5b
  it('emits the class with the override type, attributes and a trailing Extensions member', () => {
    const ir = irWith({
      AssembleOptions: options(
        [
          { name: 'addTooltips', optional: true, type: { kind: 'boolean' }, doc: 'Whether to add tooltips (default: false)' },
          { name: 'continuousMarkCrossSection', optional: true, type: crossSection },
          { name: 'labels', optional: true, type: { kind: 'record', value: { kind: 'string' } } },
          { name: 'mode', optional: true, type: { kind: 'literalUnion', values: ['fit', 'fill'] } },
        ],
        'Options for the assemblers.',
      ),
    });
    const result = emitOptions(
      ir,
      overrides({ unions: { 'AssembleOptions.continuousMarkCrossSection': 'Graspea.Flint.ContinuousMarkCrossSection' } }),
    );
    assert.deepEqual(result.files.map((f) => f.path), ['Json/FlintMapJsonContext.g.cs', 'Options/AssembleOptions.g.cs']);
    assert.equal(
      fileContent(result, 'Options/AssembleOptions.g.cs'),
      `// <auto-generated/> flint-chart 0.5.1
#nullable enable

using System.Collections.Generic;
using System.Text.Json;
using System.Text.Json.Nodes;
using System.Text.Json.Serialization;
using Graspea.Flint.Serialization;

namespace Graspea.Flint;

/// <summary>Options for the assemblers.</summary>
[JsonNumberHandling(JsonNumberHandling.Strict)]
public sealed partial class AssembleOptions
{
    /// <summary>Whether to add tooltips (default: false)</summary>
    [JsonPropertyName("addTooltips")]
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public bool? AddTooltips { get; set; }

    /// <summary>The <c>continuousMarkCrossSection</c> member.</summary>
    [JsonPropertyName("continuousMarkCrossSection")]
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public Graspea.Flint.ContinuousMarkCrossSection? ContinuousMarkCrossSection { get; set; }

    /// <summary>The <c>labels</c> member.</summary>
    [JsonPropertyName("labels")]
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonConverter(typeof(VerbatimKeyDictionaryConverter<string>))]
    public Dictionary<string, string>? Labels { get; set; }

    /// <summary>The <c>mode</c> member.</summary>
    /// <remarks>One of: <c>fit</c>, <c>fill</c>.</remarks>
    [JsonPropertyName("mode")]
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public string? Mode { get; set; }

    /// <summary>Members this version does not model, kept for round-trips; written after the known members.</summary>
    [JsonExtensionData]
    public Dictionary<string, JsonElement>? Extensions { get; set; }
}
`,
    );
    assert.deepEqual(result.apiLines, [
      'Graspea.Flint.AssembleOptions',
      'Graspea.Flint.AssembleOptions.AssembleOptions() -> void',
      'Graspea.Flint.AssembleOptions.AddTooltips.get -> bool?',
      'Graspea.Flint.AssembleOptions.AddTooltips.set -> void',
      'Graspea.Flint.AssembleOptions.ContinuousMarkCrossSection.get -> Graspea.Flint.ContinuousMarkCrossSection?',
      'Graspea.Flint.AssembleOptions.ContinuousMarkCrossSection.set -> void',
      'Graspea.Flint.AssembleOptions.Labels.get -> System.Collections.Generic.Dictionary<string!, string!>?',
      'Graspea.Flint.AssembleOptions.Labels.set -> void',
      'Graspea.Flint.AssembleOptions.Mode.get -> string?',
      'Graspea.Flint.AssembleOptions.Mode.set -> void',
      'Graspea.Flint.AssembleOptions.Extensions.get -> System.Collections.Generic.Dictionary<string!, System.Text.Json.JsonElement>?',
      'Graspea.Flint.AssembleOptions.Extensions.set -> void',
    ]);
  });

  // source: design §7.6 rule 6 and §10.4 test 5c (two members colliding after Pascal fail with both paths)
  it('fails with both IR paths when two members collide after Pascal', () => {
    const ir = irWith({
      AssembleOptions: options([
        { name: 'log_scale', optional: true, type: { kind: 'boolean' } },
        { name: 'logScale', optional: true, type: { kind: 'boolean' } },
      ]),
    });
    assert.throws(
      () => emitOptions(ir, emptyOverrides()),
      (e: Error) => e.message.includes('AssembleOptions.log_scale') && e.message.includes('AssembleOptions.logScale'),
    );
  });

  // source: design §7.4 (any/unknown fail generation unless overrides.json maps them) and §10.4 test 5d
  it('fails on an any member without an override and maps it to JsonNode with one', () => {
    const ir = irWith({ AssembleOptions: options([{ name: 'extra', optional: true, type: { kind: 'any' } }]) });
    assert.throws(() => emitOptions(ir, emptyOverrides()), /AssembleOptions\.extra/);
    const content = fileContent(emitOptions(ir, overrides({ unions: { 'AssembleOptions.extra': 'JsonNode' } })), 'Options/AssembleOptions.g.cs');
    // source: design §5.1 table (pass-through values are written with WriteTo, never with the caller's options)
    assert.match(content, /\[JsonConverter\(typeof\(JsonNodePassThroughConverter\)\)\]\n    public JsonNode\? Extra \{ get; set; \}/);
  });

  // source: design §7.4 property kind rule and §10.4 test 5e
  it('fails with both IR paths on a key that is binary on one backend and discrete on another', () => {
    const ir = syntheticIr();
    ir.catalog.chartTypes[0].backends.excel.properties = [
      { key: 'showPoints', label: 'Points', type: 'discrete', options: [{ label: 'Yes', value: true }] },
    ];
    assert.throws(
      () => checkPropertyKinds(ir, emptyOverrides()),
      (e: Error) =>
        e.message.includes('catalog.chartTypes[Line Chart].backends.vegalite.properties[showPoints]') &&
        e.message.includes('catalog.chartTypes[Line Chart].backends.excel.properties[showPoints]'),
    );
    assert.doesNotThrow(() => checkPropertyKinds(ir, overrides({ unions: { 'Line Chart/property/showPoints': 'JsonNode' } })));
  });

  // source: design §7.4 (nested object literal -> nested class <Parent><Prop>; refs to named types; T[] -> T[]?)
  it('emits nested object literals as <Parent><Prop> classes and arrays of named types', () => {
    const ir = irWith({
      ThemeSpec: options([
        { name: 'furniture', optional: true, type: { kind: 'array', element: { kind: 'ref', name: 'ThemeFurniture' } } },
        {
          name: 'interaction',
          optional: true,
          type: { kind: 'object', props: [{ name: 'tooltipFormat', optional: true, type: { kind: 'string' } }] },
        },
        { name: 'sizeRange', optional: true, type: { kind: 'tuple', elements: [{ kind: 'number' }, { kind: 'number' }] } },
      ]),
      ThemeFurniture: options([{ name: 'kind', optional: false, type: { kind: 'literalUnion', values: ['mastheadTab'] } }]),
    });
    const result = emitOptions(ir, emptyOverrides());
    assert.deepEqual(result.files.map((f) => f.path), [
      'Json/FlintMapJsonContext.g.cs',
      'Theming/ThemeFurniture.g.cs',
      'Theming/ThemeSpec.g.cs',
      'Theming/ThemeSpecInteraction.g.cs',
    ]);
    const spec = fileContent(result, 'Theming/ThemeSpec.g.cs');
    assert.match(spec, /^namespace Graspea\.Flint\.Theming;$/m);
    assert.match(spec, /public ThemeFurniture\[\]\? Furniture \{ get; set; \}/);
    assert.match(spec, /public ThemeSpecInteraction\? Interaction \{ get; set; \}/);
    assert.match(spec, /public double\[\]\? SizeRange \{ get; set; \}/);
    assert.ok(result.apiLines.includes('Graspea.Flint.Theming.ThemeSpec.Furniture.get -> Graspea.Flint.Theming.ThemeFurniture![]?'));
    assert.ok(result.apiLines.includes('Graspea.Flint.Theming.ThemeSpecInteraction.TooltipFormat.get -> string?'));
    assert.deepEqual(result.ownedTypes, [
      'Graspea.Flint.Theming.ThemeFurniture',
      'Graspea.Flint.Theming.ThemeSpec',
      'Graspea.Flint.Theming.ThemeSpecInteraction',
    ]);
  });

  // source: design §7.4 (structurally identical {width,height} -> ChartSize via overrides.json)
  it('maps a dedup path to ChartSize and refuses a dedup path of another shape', () => {
    const size = {
      kind: 'object' as const,
      props: [
        { name: 'height', optional: false, type: { kind: 'number' as const } },
        { name: 'width', optional: false, type: { kind: 'number' as const } },
      ],
    };
    const ir = irWith({ AssembleOptions: options([{ name: 'facetFixedPadding', optional: true, type: size }]) });
    const dedup = overrides({ dedup: { 'Graspea.Flint.ChartSize': ['AssembleOptions.facetFixedPadding'] } });
    assert.match(fileContent(emitOptions(ir, dedup), 'Options/AssembleOptions.g.cs'), /public Graspea\.Flint\.ChartSize\? FacetFixedPadding \{ get; set; \}/);
    size.props.pop();
    assert.throws(() => emitOptions(ir, dedup), /AssembleOptions\.facetFixedPadding/);
  });

  // source: design §7.4 (Partial<X> -> X; mapped types fail unless overrides.json accepts them, here as a flattened class)
  it('flattens an accepted mapped type into <Parent><Prop> and fails without the override', () => {
    const ir = irWith({
      ThemeSpec: options([
        { name: 'label', optional: true, type: { kind: 'string' } },
        { name: 'variants', optional: true, type: { kind: 'array', element: { kind: 'ref', name: 'ThemeVariant' } } },
      ]),
      ThemeVariant: options([
        {
          name: 'then',
          optional: false,
          type: { kind: 'mapped', text: 'Partial<Omit<ThemeSpec, "label">>', props: [{ name: 'marks', optional: true, type: { kind: 'string' } }] },
        },
        { name: 'base', optional: true, type: { kind: 'partial', of: { kind: 'ref', name: 'ThemeSpec' } } },
      ]),
    });
    assert.throws(() => emitOptions(ir, emptyOverrides()), /ThemeVariant\.then/);
    const result = emitOptions(ir, overrides({ flatten: ['ThemeVariant.then'] }));
    assert.deepEqual(result.files.map((f) => f.path), [
      'Json/FlintMapJsonContext.g.cs',
      'Theming/ThemeSpec.g.cs',
      'Theming/ThemeVariant.g.cs',
      'Theming/ThemeVariantThen.g.cs',
    ]);
    const variant = fileContent(result, 'Theming/ThemeVariant.g.cs');
    assert.match(variant, /public ThemeVariantThen\? Then \{ get; set; \}/);
    assert.match(variant, /public ThemeSpec\? Base \{ get; set; \}/);
  });

  // source: design §7.4 (a record of unknown values needs an explicit JsonNode mapping; map members get the converter)
  it('emits nested records with the closed-generic converter of the value type', () => {
    const ir = irWith({
      ThemeSpec: options([{ name: 'chartDefaults', optional: true, type: { kind: 'ref', name: 'ThemeChartDefaults' } }]),
      ThemeChartDefaults: { kind: 'record', value: { kind: 'record', value: { kind: 'unknown' } } },
    });
    assert.throws(() => emitOptions(ir, emptyOverrides()), /ThemeChartDefaults\{\*\}\{\*\}/);
    const content = fileContent(emitOptions(ir, overrides({ unions: { 'ThemeChartDefaults{*}{*}': 'JsonNode' } })), 'Theming/ThemeSpec.g.cs');
    assert.match(content, /\[JsonConverter\(typeof\(VerbatimKeyDictionaryConverter<Dictionary<string, JsonNode\?>>\)\)\]/);
    assert.match(content, /public Dictionary<string, Dictionary<string, JsonNode\?>>\? ChartDefaults \{ get; set; \}/);
  });

  // source: design §5.1 (map values are serialised through the library's own source-generated metadata, so every
  // converter argument must be registered in a library context; the emitter that writes the converter owns the
  // registration, in its own context because System.Text.Json reads [JsonSerializable] from one declaration only)
  it('registers every map value type of the generated members in FlintMapJsonContext', () => {
    const ir = irWith({
      ThemeSpec: options([
        { name: 'chartDefaults', optional: true, type: { kind: 'ref', name: 'ThemeChartDefaults' } },
        { name: 'foos', optional: true, type: { kind: 'record', value: { kind: 'ref', name: 'ThemeFoo' } } },
        { name: 'labels', optional: true, type: { kind: 'record', value: { kind: 'string' } } },
      ]),
      ThemeChartDefaults: { kind: 'record', value: { kind: 'record', value: { kind: 'unknown' } } },
      ThemeFoo: options([{ name: 'bars', optional: true, type: { kind: 'record', value: { kind: 'string' } } }]),
    });
    const result = emitOptions(ir, overrides({ unions: { 'ThemeChartDefaults{*}{*}': 'JsonNode' } }));
    assert.equal(
      fileContent(result, 'Json/FlintMapJsonContext.g.cs'),
      `// <auto-generated/> flint-chart 0.5.1
#nullable enable

using System.Text.Json.Serialization;

namespace Graspea.Flint.Serialization;

/// <summary>Map value types of the generated members, resolved by <see cref="VerbatimKeyDictionaryConverter{T}"/>.</summary>
[JsonSourceGenerationOptions(DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull, NumberHandling = JsonNumberHandling.Strict)]
[JsonSerializable(typeof(Graspea.Flint.Theming.ThemeFoo))]
[JsonSerializable(typeof(System.Collections.Generic.Dictionary<string, System.Text.Json.Nodes.JsonNode?>))]
[JsonSerializable(typeof(string))]
internal sealed partial class FlintMapJsonContext : JsonSerializerContext;
`,
    );
    assert.ok(!result.apiLines.some((l) => l.includes('FlintMapJsonContext')));
  });

  // source: design §5.1 (the converter always compiles against the context, so it exists without map members)
  it('emits FlintMapJsonContext with string alone when no member is a map', () => {
    const ir = irWith({ AssembleOptions: options([{ name: 'addTooltips', optional: true, type: { kind: 'boolean' } }]) });
    assert.match(fileContent(emitOptions(ir, emptyOverrides()), 'Json/FlintMapJsonContext.g.cs'), /\]\n\[JsonSerializable\(typeof\(string\)\)\]\ninternal sealed partial class FlintMapJsonContext/);
  });

  // source: design §7.5 (options overwritten by backends are documented) and §7.4 (ThemeCompileDefaults is
  // Partial<AssembleOptions> flattened, so its members are the same options and are overwritten the same way)
  it('remarks the ignored options on AssembleOptions and on ThemeCompileDefaults', () => {
    const member = { name: 'maxStretchX', optional: true, type: { kind: 'number' as const } };
    const ir = irWith({
      AssembleOptions: options([member]),
      ThemeSpec: options([{ name: 'compileDefaults', optional: true, type: { kind: 'ref', name: 'ThemeCompileDefaults' } }]),
      ThemeCompileDefaults: options([member]),
    });
    ir.catalog.ignoredOptions = { maxStretchX: ['vegalite', 'echarts'] };
    const remark = /\/\/\/ <remarks>Overwritten by the vegalite and echarts backends\.<\/remarks>\n    \[JsonPropertyName\("maxStretchX"\)\]/;
    const result = emitOptions(ir, emptyOverrides());
    assert.match(fileContent(result, 'Options/AssembleOptions.g.cs'), remark);
    assert.match(fileContent(result, 'Theming/ThemeCompileDefaults.g.cs'), remark);
  });

  // source: design §7.5 (docs overrides add facts the d.ts gets wrong)
  it('appends a docs override as a remark', () => {
    const ir = irWith({ AssembleOptions: options([{ name: 'maxStretch', optional: true, type: { kind: 'number' }, doc: 'Cap (default: 2)' }]) });
    const content = fileContent(emitOptions(ir, overrides({ docs: { 'AssembleOptions.maxStretch': 'The real default is 1.5.' } })), 'Options/AssembleOptions.g.cs');
    assert.match(content, /\/\/\/ <remarks>The real default is 1\.5\.<\/remarks>\n    \[JsonPropertyName\("maxStretch"\)\]/);
  });

  // source: design §7.4 (overrides are reviewed lines; one that matches nothing is a stale review)
  it('fails on an override path that matches no member', () => {
    const ir = irWith({ AssembleOptions: options([{ name: 'addTooltips', optional: true, type: { kind: 'boolean' } }]) });
    assert.throws(() => emitOptions(ir, overrides({ unions: { 'AssembleOptions.gone': 'JsonNode' } })), /AssembleOptions\.gone/);
  });
});

describe('overrides', () => {
  // source: design §7.2 (overrides.json validated against overrides.schema.json)
  it('rejects an unknown top-level key', () => {
    assert.throws(() => parseOverrides({ unionz: {} }), /unionz/);
  });

  it('fills absent sections with empty values', () => {
    assert.deepEqual(parseOverrides({}), emptyOverrides());
  });
});
