import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { emitConstants } from '../src/emit/constants.ts';
import { emptyOverrides } from '../src/overrides.ts';
import type { Ir } from '../src/ir.ts';
import { syntheticIr } from './support/synthetic-ir.ts';

function irWithLiterals(): Ir {
  const ir = syntheticIr();
  ir.types = {
    ChartEncoding: {
      kind: 'object',
      props: [
        { name: 'aggregate', optional: true, type: { kind: 'literalUnion', values: ['count', 'mean'] } },
        { name: 'sortOrder', optional: true, type: { kind: 'literalUnion', values: ['ascending'] } },
        { name: 'type', optional: true, type: { kind: 'literalUnion', values: ['temporal'] } },
      ],
    },
    ContinuousMarkCrossSection: {
      kind: 'union',
      members: [
        { kind: 'number' },
        {
          kind: 'object',
          props: [{ name: 'seriesCountAxis', optional: true, type: { kind: 'literalUnion', values: ['x', 'auto'] } }],
        },
      ],
    },
  };
  return ir;
}

describe('emit/constants', () => {
  // source: design §7.4 (constants: partial files adding generated members to the hand-written structs) and §4.1
  it('emits one partial struct file per string-backed struct plus FlintUpstream', () => {
    const result = emitConstants(irWithLiterals());
    assert.deepEqual(result.files.map((f) => f.path), [
      'Constants/Aggregate.g.cs',
      'Constants/Channel.g.cs',
      'Constants/ChartType.g.cs',
      'Constants/EncodingType.g.cs',
      'Constants/FlintUpstream.g.cs',
      'Constants/SemanticType.g.cs',
      'Constants/SeriesCountAxis.g.cs',
      'Constants/SortOrder.g.cs',
      'Constants/ThemePreset.g.cs',
    ]);
  });

  // source: design §4.1 (public static readonly ChartType LineChart = new("Line Chart"); generated) and §7.6 rule 2
  it('emits chart type constants from the catalog', () => {
    const file = emitConstants(irWithLiterals()).files.find((f) => f.path === 'Constants/ChartType.g.cs')!;
    assert.equal(
      file.content,
      `// <auto-generated/> flint-chart 0.5.1
#nullable enable

namespace Graspea.Flint;

public readonly partial record struct ChartType
{
    /// <summary>The <c>Line Chart</c> template; backends: vegalite, excel.</summary>
    public static readonly ChartType LineChart = new("Line Chart");
}
`,
    );
  });

  // source: design §7.6 rule 5 (semantic types verbatim, presets Pascal(id)) and §4.1 struct table
  it('names semantic types verbatim, presets and channels by Pascal, literals from the IR unions', () => {
    const result = emitConstants(irWithLiterals());
    const text = (p: string) => result.files.find((f) => f.path === p)!.content;
    assert.match(text('Constants/SemanticType.g.cs'), /public static readonly SemanticType YearMonth = new\("YearMonth"\);/);
    assert.match(text('Constants/ThemePreset.g.cs'), /public static readonly ThemePreset PowerbiLight = new\("powerbi-light"\);/);
    assert.match(text('Constants/Channel.g.cs'), /public static readonly Channel Color = new\("color"\);/);
    assert.match(text('Constants/Aggregate.g.cs'), /public static readonly Aggregate Mean = new\("mean"\);/);
    assert.match(text('Constants/EncodingType.g.cs'), /public static readonly EncodingType Temporal = new\("temporal"\);/);
    assert.match(text('Constants/SortOrder.g.cs'), /public static readonly SortOrder Ascending = new\("ascending"\);/);
    assert.match(text('Constants/SeriesCountAxis.g.cs'), /public static readonly SeriesCountAxis Auto = new\("auto"\);/);
  });

  // source: design §6 (invalid_literal: a value outside the IR literal set); the set is internal, for the validator
  it('lists the IR literals of each literal-union struct for the validator', () => {
    const result = emitConstants(irWithLiterals());
    const text = (p: string) => result.files.find((f) => f.path === p)!.content;
    assert.match(
      text('Constants/Aggregate.g.cs'),
      /    internal static readonly System\.Collections\.Frozen\.FrozenSet<string> Literals = System\.Collections\.Frozen\.FrozenSet\.ToFrozenSet\(\["count", "mean"\], StringComparer\.Ordinal\);\n/,
    );
    assert.match(text('Constants/SeriesCountAxis.g.cs'), /Literals = .*\["x", "auto"\]/);
    assert.doesNotMatch(text('Constants/ChartType.g.cs'), /Literals/);
    assert.ok(!result.apiLines.some((l) => l.includes('Literals')));
  });

  // source: design §4.1 (FlintUpstream.Version is a generated constant, "0.5.1")
  it('emits FlintUpstream.Version and its API lines', () => {
    const result = emitConstants(irWithLiterals());
    assert.match(result.files.find((f) => f.path === 'Constants/FlintUpstream.g.cs')!.content, /public const string Version = "0\.5\.1";/);
    assert.ok(result.apiLines.includes('const Graspea.Flint.FlintUpstream.Version = "0.5.1" -> string!'));
    assert.ok(result.apiLines.includes('static readonly Graspea.Flint.ChartType.LineChart -> Graspea.Flint.ChartType'));
    assert.deepEqual(result.ownedTypes, ['Graspea.Flint.FlintUpstream']);
    assert.ok(result.ownedConstantStructs.includes('Graspea.Flint.ChartType'));
  });

  // source: design §7.6 rule 6 (two constants equal after Pascal fail generation with the IR paths)
  it('fails with both IR paths when two constants collide', () => {
    const ir = irWithLiterals();
    ir.catalog.channels.push('Color');
    assert.throws(
      () => emitConstants(ir),
      (e: Error) => e.message.includes('catalog.channels[color]') && e.message.includes('catalog.channels[Color]'),
    );
  });

  // source: design §4.1 (Name is the struct's own member; a constant cannot take it)
  it('fails when a constant would take a member name of the hand-written struct', () => {
    const ir = irWithLiterals();
    ir.catalog.channels.push('name');
    assert.throws(() => emitConstants(ir), /catalog\.channels\[name\]/);
  });

  // source: design §7.6 rule 6 (a remaining collision is fixed with a reviewed rename in overrides.json)
  it('applies a rename override to a colliding constant', () => {
    const ir = irWithLiterals();
    ir.catalog.semanticTypes.push({ name: 'Name', t0: 'Categorical', t1: 'Entity', visEncodings: ['nominal'] });
    assert.throws(() => emitConstants(ir), /catalog\.semanticTypes\[Name\]/);
    const result = emitConstants(ir, { ...emptyOverrides(), renames: { 'catalog.semanticTypes[Name]': 'NameType' } });
    assert.match(
      result.files.find((f) => f.path === 'Constants/SemanticType.g.cs')!.content,
      /public static readonly SemanticType NameType = new\("Name"\);/,
    );
  });

  // source: owner decision 2026-10-17 (theme presets take reviewed renames: powerbi-light -> PowerBiLight; the wire id stays)
  it('applies a rename override to a theme preset and keeps the wire id', () => {
    const result = emitConstants(irWithLiterals(), { ...emptyOverrides(), renames: { 'catalog.themePresets[powerbi-light]': 'PowerBiLight' } });
    const text = result.files.find((f) => f.path === 'Constants/ThemePreset.g.cs')!.content;
    assert.match(text, /public static readonly ThemePreset PowerBiLight = new\("powerbi-light"\);/);
    assert.doesNotMatch(text, /PowerbiLight/);
    assert.ok(result.apiLines.includes('static readonly Graspea.Flint.ThemePreset.PowerBiLight -> Graspea.Flint.ThemePreset'));
  });

  // source: design §7.6 rule 6 (an override entry that matches nothing fails generation)
  it('fails on a theme preset rename that matches no preset', () => {
    assert.throws(
      () => emitConstants(irWithLiterals(), { ...emptyOverrides(), renames: { 'catalog.themePresets[powerbi]': 'PowerBi' } }),
      /catalog\.themePresets\[powerbi\]/,
    );
  });
});
