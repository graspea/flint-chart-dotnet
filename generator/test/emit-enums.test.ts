import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { emitEnums } from '../src/emit/enums.ts';
import { emptyOverrides } from '../src/overrides.ts';
import type { Ir } from '../src/ir.ts';
import { syntheticIr } from './support/synthetic-ir.ts';

/** Map: a discrete property whose values are arrays (named from their labels) and whose sets differ per backend. */
function mapIr(): Ir {
  const ir = syntheticIr();
  ir.catalog.chartTypes = [
    {
      name: 'Map',
      backends: {
        vegalite: {
          channels: ['x'],
          properties: [
            {
              key: 'projectionCenter',
              label: 'Center',
              type: 'discrete',
              options: [
                { label: 'Default', omitted: true },
                { label: 'Europe [10, 50]', value: [10, 50] },
                { label: 'World (Pacific) [150, 0]', value: [150, 0] },
              ],
            },
          ],
        },
        excel: {
          channels: ['x'],
          properties: [
            {
              key: 'projectionCenter',
              label: 'Center',
              type: 'discrete',
              options: [
                { label: 'Europe [10, 50]', value: [10, 50] },
                { label: 'Default', value: 'default' },
                { label: 'Horizontal', value: 0 },
                { label: 'Show (default)', value: true },
              ],
            },
          ],
        },
      },
    },
  ];
  return ir;
}

describe('emit/enums', () => {
  // source: design §4.2 (public enum LineChartInterpolate { Default, … }; internal value table, Default -> null so the key
  // is removed), §7.4 (enum + internal value table per distinct template-and-key discrete pair) and §8.2 (generated surface
  // additive per upstream release, so every member carries an explicit number)
  it('emits the enum and its value table for each discrete template property', () => {
    const result = emitEnums(syntheticIr(), emptyOverrides());
    assert.deepEqual(result.files.map((f) => f.path), ['Enums/LineChartInterpolate.g.cs']);
    assert.equal(
      result.files[0].content,
      `// <auto-generated/> flint-chart 0.5.1
#nullable enable

using System.Text.Json.Nodes;

namespace Graspea.Flint;

/// <summary>The values of the <c>interpolate</c> property ("Curve") of the <c>Line Chart</c> template.</summary>
public enum LineChartInterpolate
{
    /// <summary>Omits the key, so the backend applies its default ("Default").</summary>
    Default = 0,

    /// <summary><c>"monotone"</c> ("Monotone").</summary>
    Monotone = 1,
}

internal static class LineChartInterpolateValues
{
    internal static JsonNode? ToJson(LineChartInterpolate value) => value switch
    {
        LineChartInterpolate.Default => null,
        LineChartInterpolate.Monotone => JsonValue.Create("monotone"),
        _ => throw new ArgumentOutOfRangeException(nameof(value), value, null),
    };
}
`,
    );
    assert.deepEqual(result.apiLines, [
      'Graspea.Flint.LineChartInterpolate',
      'Graspea.Flint.LineChartInterpolate.Default = 0 -> Graspea.Flint.LineChartInterpolate',
      'Graspea.Flint.LineChartInterpolate.Monotone = 1 -> Graspea.Flint.LineChartInterpolate',
    ]);
    assert.deepEqual(result.ownedTypes, ['Graspea.Flint.LineChartInterpolate']);
  });

  // source: design §7.4 (the enum is the union of the option values across backends; Validate(backend) reports
  // invalid_option_value for a member that backend lacks), §7.6 rule 4 (member names from string values or labels;
  // "default" -> DefaultLiteral) and normalize-properties.ts (an array value is accepted only by reference, so the label
  // is written, which upstream coerces to the option)
  it('takes the union across backends and names non-string values from their labels', () => {
    const content = emitEnums(mapIr(), emptyOverrides()).files[0].content;
    assert.equal(
      content.slice(content.indexOf('public enum')),
      `public enum MapProjectionCenter
{
    /// <summary>Omits the key, so the backend applies its default ("Default").</summary>
    Default = 0,

    /// <summary>Writes the label <c>"Europe [10, 50]"</c>, which flint-chart maps to <c>[10,50]</c>.</summary>
    Europe = 1,

    /// <summary>Writes the label <c>"World (Pacific) [150, 0]"</c>, which flint-chart maps to <c>[150,0]</c>. Not offered by excel (<c>invalid_option_value</c>).</summary>
    WorldPacific = 2,

    /// <summary><c>"default"</c> ("Default"). Not offered by vegalite (<c>invalid_option_value</c>).</summary>
    DefaultLiteral = 3,

    /// <summary><c>0</c> ("Horizontal"). Not offered by vegalite (<c>invalid_option_value</c>).</summary>
    Horizontal = 4,

    /// <summary><c>true</c> ("Show (default)"). Not offered by vegalite (<c>invalid_option_value</c>).</summary>
    Show = 5,
}

internal static class MapProjectionCenterValues
{
    internal static JsonNode? ToJson(MapProjectionCenter value) => value switch
    {
        MapProjectionCenter.Default => null,
        MapProjectionCenter.Europe => JsonValue.Create("Europe [10, 50]"),
        MapProjectionCenter.WorldPacific => JsonValue.Create("World (Pacific) [150, 0]"),
        MapProjectionCenter.DefaultLiteral => JsonValue.Create("default"),
        MapProjectionCenter.Horizontal => JsonValue.Create(0),
        MapProjectionCenter.Show => JsonValue.Create(true),
        _ => throw new ArgumentOutOfRangeException(nameof(value), value, null),
    };
}
`,
    );
  });

  // source: design §7.4 (the 0.5.1 override maps the kind mismatch of Radar Chart filled to a raw JsonNode setter, so no
  // enum is emitted for it)
  it('emits no enum for a property mapped to JsonNode', () => {
    const ir = syntheticIr();
    ir.catalog.chartTypes[0].backends.excel.properties = [{ key: 'interpolate', label: 'Curve', type: 'binary' }];
    const overrides = { ...emptyOverrides(), unions: { 'Line Chart/property/interpolate': 'JsonNode' } };
    assert.deepEqual(emitEnums(ir, overrides).files, []);
  });

  // source: design §7.6 rules 3 and 6 (renames["<Template>/enum/<key>"] names the enum, its file and its value table)
  it('emits a renamed enum under its new name', () => {
    const result = emitEnums(syntheticIr(), { ...emptyOverrides(), renames: { 'Line Chart/enum/interpolate': 'Curve' } });
    assert.deepEqual(result.files.map((f) => f.path), ['Enums/Curve.g.cs']);
    assert.match(result.files[0].content, /public enum Curve\n/);
    assert.match(result.files[0].content, /internal static class CurveValues\n/);
    assert.equal(result.apiLines[0], 'Graspea.Flint.Curve');
  });

  // source: owner decision (TreeOrient members get readable names through overrides.json renames; the wire values stay)
  // and design §7.6 rule 6 (an override names the C# symbol only)
  it('renames an enum member through renames["<Template>/enum/<key>/<value>"] and keeps its wire value', () => {
    const result = emitEnums(syntheticIr(), { ...emptyOverrides(), renames: { 'Line Chart/enum/interpolate/monotone': 'Smooth' } });
    const content = result.files[0].content;
    assert.match(content, /    Smooth = 1,\n/);
    assert.match(content, /LineChartInterpolate\.Smooth => JsonValue\.Create\("monotone"\),/);
    assert.doesNotMatch(content, /Monotone =|\.Monotone/);
    assert.deepEqual(result.apiLines.slice(1), [
      'Graspea.Flint.LineChartInterpolate.Default = 0 -> Graspea.Flint.LineChartInterpolate',
      'Graspea.Flint.LineChartInterpolate.Smooth = 1 -> Graspea.Flint.LineChartInterpolate',
    ]);
  });

  // source: design §7.6 rule 6 (a rename that collides fails; an override that matches nothing fails generation)
  it('fails on an enum member rename that collides or matches nothing', () => {
    assert.throws(
      () => emitEnums(syntheticIr(), { ...emptyOverrides(), renames: { 'Line Chart/enum/interpolate/monotone': 'Default' } }),
      /Enum member collision "Default"/,
    );
    assert.throws(
      () => emitEnums(syntheticIr(), { ...emptyOverrides(), renames: { 'Line Chart/enum/interpolate/linear': 'Straight' } }),
      /renames\["Line Chart\/enum\/interpolate\/linear"\]: template rename that matches nothing/,
    );
  });

  // source: design §7.6 rule 6 (two enum members equal fail generation with the IR paths)
  it('fails when two option values give the same member name', () => {
    const ir = syntheticIr();
    ir.catalog.chartTypes[0].backends.vegalite.properties[0].options!.push({ label: 'Mono', value: 'Monotone' });
    assert.throws(() => emitEnums(ir, emptyOverrides()), /properties\[interpolate\]\.options\[monotone\].*options\[Monotone\]/);
  });

  // source: design §8.2 (the generated surface is additive per upstream release; renumbering a shipped member is a binary
  // break) and the PublicAPI.Shipped.txt line format of the public-api emitter: shipped numbers are kept, a new member takes
  // the next number above every shipped one, wherever upstream inserts it
  it('keeps shipped member numbers and numbers a value inserted upstream after them', () => {
    const ir = syntheticIr();
    ir.catalog.chartTypes[0].backends.vegalite.properties[0].options!.splice(1, 0, { label: 'Linear', value: 'linear' });
    const shipped = [
      '#nullable enable',
      'Graspea.Flint.LineChartInterpolate',
      'Graspea.Flint.LineChartInterpolate.Default = 0 -> Graspea.Flint.LineChartInterpolate',
      'Graspea.Flint.LineChartInterpolate.Monotone = 1 -> Graspea.Flint.LineChartInterpolate',
      'Graspea.Flint.LineChartInterpolate.Retired = 2 -> Graspea.Flint.LineChartInterpolate',
      '',
    ].join('\n');
    const result = emitEnums(ir, emptyOverrides(), shipped);
    const content = result.files[0].content;
    assert.match(content, /    Linear = 3,\n/);
    assert.match(content, /    Monotone = 1,\n/);
    assert.ok(content.indexOf('Linear = 3') < content.indexOf('Monotone = 1'), 'members stay in union order');
    assert.deepEqual(result.apiLines, [
      'Graspea.Flint.LineChartInterpolate',
      'Graspea.Flint.LineChartInterpolate.Default = 0 -> Graspea.Flint.LineChartInterpolate',
      'Graspea.Flint.LineChartInterpolate.Linear = 3 -> Graspea.Flint.LineChartInterpolate',
      'Graspea.Flint.LineChartInterpolate.Monotone = 1 -> Graspea.Flint.LineChartInterpolate',
    ]);
  });

  // source: design §4.2 (Default = omit the key, the zero value) and §8.2 (a shipped number never changes)
  it('fails when the shipped numbers cannot be kept', () => {
    const line = (member: string, n: number) => `Graspea.Flint.LineChartInterpolate.${member} = ${n} -> Graspea.Flint.LineChartInterpolate`;
    assert.throws(() => emitEnums(syntheticIr(), emptyOverrides(), line('Default', 1)), /LineChartInterpolate\.Default.*shipped as 1/);
    assert.throws(
      () => emitEnums(syntheticIr(), emptyOverrides(), [line('Monotone', 1), line('Linear', 1)].join('\n')),
      /LineChartInterpolate\.Monotone and LineChartInterpolate\.Linear.*both shipped as 1/,
    );
  });
});
