// Shared emitter helpers: file header, C# literals, XML doc comments, emitter result shape.
import type { Ir } from '../ir.ts';

export interface EmittedFile {
  /** Path relative to src/Graspea.Flint/Generated, forward slashes. */
  path: string;
  content: string;
}

export interface EmitResult {
  files: EmittedFile[];
  /** PublicAPI.txt lines for the generated public symbols. */
  apiLines: string[];
  /** Generated types (fully qualified): every API line of these types belongs to the generator. */
  ownedTypes: string[];
  /** Hand-written structs whose `static readonly` constants the generator owns. */
  ownedConstantStructs: string[];
  /** Generated members of hand-written types (`Graspea.Flint.Chart.Line`): every API line of their overloads belongs to the generator. */
  ownedMembers: string[];
}

export function emptyResult(): EmitResult {
  return { files: [], apiLines: [], ownedTypes: [], ownedConstantStructs: [], ownedMembers: [] };
}

export function mergeResults(results: EmitResult[]): EmitResult {
  return {
    files: results.flatMap((r) => r.files),
    apiLines: results.flatMap((r) => r.apiLines),
    ownedTypes: results.flatMap((r) => r.ownedTypes),
    ownedConstantStructs: results.flatMap((r) => r.ownedConstantStructs),
    ownedMembers: results.flatMap((r) => r.ownedMembers),
  };
}

/** Every emitted file starts with this line (design §7.4). */
export function header(ir: Ir): string {
  return `// <auto-generated/> ${ir.upstream.package} ${ir.upstream.version}\n#nullable enable\n`;
}

/** Backend id -> member of the hand-written FlintBackend enum. */
const BACKEND_MEMBERS: Readonly<Record<string, string>> = {
  vegalite: 'VegaLite',
  echarts: 'ECharts',
  chartjs: 'ChartJs',
  plotly: 'Plotly',
  excel: 'Excel',
};

export function backendMember(id: string): string {
  const member = BACKEND_MEMBERS[id];
  if (!member) throw new Error(`catalog.backends[${id}] has no FlintBackend member; extend FlintBackend and src/emit/common.ts.`);
  return `FlintBackend.${member}`;
}

/** A C# regular string literal; everything outside printable ASCII is escaped. */
export function csString(s: string): string {
  let out = '"';
  for (const ch of s) {
    const code = ch.codePointAt(0)!;
    if (ch === '"') out += '\\"';
    else if (ch === '\\') out += '\\\\';
    else if (code >= 0x20 && code < 0x7f) out += ch;
    else if (code > 0xffff) out += `\\U${code.toString(16).padStart(8, '0')}`;
    else out += `\\u${code.toString(16).padStart(4, '0')}`;
  }
  return out + '"';
}

/** A C# double literal for a finite JS number. */
export function csNumber(n: number): string {
  if (!Number.isFinite(n)) throw new Error(`Cannot emit the non-finite number ${n}.`);
  return String(n);
}

/** Doc text as XML: escaped, `code` spans as <c>, line separators normalised. */
export function xmlText(text: string): string {
  return text
    .replace(/[\u2028\u2029\u0085\r]/g, '\n')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/\{@link\s+([^}\s]+)\s*\}/g, '<c>$1</c>')
    .replace(/`([^`\n]+)`/g, '<c>$1</c>');
}

/** `/// <summary>` (and optional `<remarks>`) lines for a member at the given indent. */
export function docComment(indent: string, summary: string, remarks?: string): string {
  const block = (tag: string, text: string) => {
    const lines = xmlText(text).split('\n').map((l) => l.trimEnd());
    while (lines.length > 0 && lines[lines.length - 1] === '') lines.pop();
    if (lines.length === 1) return [`${indent}/// <${tag}>${lines[0]}</${tag}>`];
    return [`${indent}/// <${tag}>`, ...lines.map((l) => (l === '' ? `${indent}///` : `${indent}/// ${l.trimStart()}`)), `${indent}/// </${tag}>`];
  };
  const lines = block('summary', summary);
  if (remarks) lines.push(...block('remarks', remarks));
  return lines.join('\n') + '\n';
}
