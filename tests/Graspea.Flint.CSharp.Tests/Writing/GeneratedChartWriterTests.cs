namespace Graspea.Flint.CSharp.Tests.Writing;

/// <summary>The source the generator adds per class (design §12.6.3), written by the conversion core.</summary>
public sealed class GeneratedChartWriterTests
{
    private const string Revenue = """
        {
          "data": { "values": [ { "month": "2024-01-01", "revenue": 1200.50, "region": "EU" } ] },
          "semantic_types": { "month": "YearMonth", "revenue": "Amount" },
          "chart_spec": {
            "chartType": "Line Chart",
            "title": "Revenue by region",
            "encodings": { "x": "month", "y": { "field": "revenue" }, "color": { "field": "region" } },
            "baseSize": { "width": 800, "height": 400 },
            "chartProperties": { "interpolate": "monotone" }
          },
          "theme_spec": "economist"
        }
        """;

    private static readonly GeneratedTarget Charts = new("Charts", [], "RevenueChart", "public", "Charts/revenue.flint.json", "0.5.1.1");

    private static SpecDocument Spec(string json) => new(JsonReader.Parse(json));

    // source: design §12.6.3 (mode A: the Row record of §12.4.3, Template built on first use with LazyInitializer over the
    // reserved __flint_template, the trimming attributes on the get accessor, Build, BuildAsync, WriteAsync and Validate
    // over Template; no using directive, every type global::-qualified; [Experimental("FLINTEXP001")] on every generated
    // member, D7.11) and the fluent chain of §12.5.3's example in the parameter data mode, ending in ToTemplate()
    [Test]
    public void Write_ModeA_WritesTheRowRecordAndTheTemplateMembers()
    {
        var spec = Spec(Revenue);

        var code = GeneratedChartWriter.Write(spec, Charts, RowInference.Infer(spec, replay: false));

        Assert.That(code, Is.EqualTo("""
            // <auto-generated/> Graspea.Flint.Generators 0.5.1.1 from Charts/revenue.flint.json
            #nullable enable

            namespace Charts;

            static partial class RevenueChart
            {
                /// <summary>A row of the chart, inferred from Charts/revenue.flint.json.</summary>
                /// <param name="Month">The <c>month</c> field.</param>
                /// <param name="Revenue">The <c>revenue</c> field.</param>
                /// <param name="Region">The <c>region</c> field.</param>
                [global::System.Diagnostics.CodeAnalysis.ExperimentalAttribute("FLINTEXP001")]
                public sealed record Row(
                    [property: global::System.Text.Json.Serialization.JsonPropertyNameAttribute("month")] global::System.DateOnly Month,
                    [property: global::System.Text.Json.Serialization.JsonPropertyNameAttribute("revenue")] decimal Revenue,
                    [property: global::System.Text.Json.Serialization.JsonPropertyNameAttribute("region")] string Region);

                [global::System.Diagnostics.CodeAnalysis.ExperimentalAttribute("FLINTEXP001")]
                private static global::Graspea.Flint.ChartTemplate<Row>? __flint_template;

                /// <summary>The chart of Charts/revenue.flint.json without rows, built on first use; bind rows per call.</summary>
                [global::System.Diagnostics.CodeAnalysis.ExperimentalAttribute("FLINTEXP001")]
                public static global::Graspea.Flint.ChartTemplate<Row> Template
                {
                    [global::System.Diagnostics.CodeAnalysis.RequiresUnreferencedCodeAttribute("Row types are serialised by reflection; use the JsonTypeInfo overload for trimmed or AOT hosts.")]
                    [global::System.Diagnostics.CodeAnalysis.RequiresDynamicCodeAttribute("Row types are serialised by reflection; use the JsonTypeInfo overload for trimmed or AOT hosts.")]
                    get => global::System.Threading.LazyInitializer.EnsureInitialized(ref __flint_template, static () =>
                        global::Graspea.Flint.Chart.Line<Row>()
                            .X(r => r.Month, global::Graspea.Flint.SemanticType.YearMonth)
                            .Y(r => r.Revenue, global::Graspea.Flint.SemanticType.Amount)
                            .Color(r => r.Region)
                            .Interpolate(global::Graspea.Flint.LineChartInterpolate.Monotone)
                            .Title("Revenue by region")
                            .BaseSize(800, 400)
                            .Theme(global::Graspea.Flint.ThemePreset.Economist)
                            .ToTemplate());
                }

                /// <summary>A new document with <paramref name="rows"/> written to JSON now.</summary>
                /// <param name="rows">The rows.</param>
                /// <returns>The document.</returns>
                [global::System.Diagnostics.CodeAnalysis.ExperimentalAttribute("FLINTEXP001")]
                [global::System.Diagnostics.CodeAnalysis.RequiresUnreferencedCodeAttribute("Row types are serialised by reflection; use the JsonTypeInfo overload for trimmed or AOT hosts.")]
                [global::System.Diagnostics.CodeAnalysis.RequiresDynamicCodeAttribute("Row types are serialised by reflection; use the JsonTypeInfo overload for trimmed or AOT hosts.")]
                public static global::Graspea.Flint.ChartAssemblyInput Build(global::System.Collections.Generic.IEnumerable<Row> rows) => Template.Bind(rows);

                /// <summary>A new document with the rows of an asynchronous source written to JSON.</summary>
                /// <param name="rows">The rows; end a database query with <c>.AsAsyncEnumerable()</c>.</param>
                /// <param name="cancellationToken">Passed to the source and checked before each row.</param>
                /// <returns>The document.</returns>
                [global::System.Diagnostics.CodeAnalysis.ExperimentalAttribute("FLINTEXP001")]
                [global::System.Diagnostics.CodeAnalysis.RequiresUnreferencedCodeAttribute("Row types are serialised by reflection; use the JsonTypeInfo overload for trimmed or AOT hosts.")]
                [global::System.Diagnostics.CodeAnalysis.RequiresDynamicCodeAttribute("Row types are serialised by reflection; use the JsonTypeInfo overload for trimmed or AOT hosts.")]
                public static global::System.Threading.Tasks.ValueTask<global::Graspea.Flint.ChartAssemblyInput> BuildAsync(global::System.Collections.Generic.IAsyncEnumerable<Row> rows, global::System.Threading.CancellationToken cancellationToken = default) =>
                    Template.BindAsync(rows, cancellationToken);

                /// <summary>Writes the document to <paramref name="utf8Json"/> with the rows streamed from their source.</summary>
                /// <param name="utf8Json">The stream.</param>
                /// <param name="rows">The rows.</param>
                /// <param name="cancellationToken">Passed to the source and to every write.</param>
                /// <returns>The write.</returns>
                [global::System.Diagnostics.CodeAnalysis.ExperimentalAttribute("FLINTEXP001")]
                [global::System.Diagnostics.CodeAnalysis.RequiresUnreferencedCodeAttribute("Row types are serialised by reflection; use the JsonTypeInfo overload for trimmed or AOT hosts.")]
                [global::System.Diagnostics.CodeAnalysis.RequiresDynamicCodeAttribute("Row types are serialised by reflection; use the JsonTypeInfo overload for trimmed or AOT hosts.")]
                public static global::System.Threading.Tasks.Task WriteAsync(global::System.IO.Stream utf8Json, global::System.Collections.Generic.IAsyncEnumerable<Row> rows, global::System.Threading.CancellationToken cancellationToken = default) =>
                    global::Graspea.Flint.Serialization.FlintJson.SerializeAsync(utf8Json, Template.BindStream(rows), cancellationToken);

                /// <summary>Validates the spec and the row metadata without rows.</summary>
                /// <param name="backend">The target backend; null means every backend that has the template.</param>
                /// <returns>The issues.</returns>
                [global::System.Diagnostics.CodeAnalysis.ExperimentalAttribute("FLINTEXP001")]
                [global::System.Diagnostics.CodeAnalysis.RequiresUnreferencedCodeAttribute("Row types are serialised by reflection; use the JsonTypeInfo overload for trimmed or AOT hosts.")]
                [global::System.Diagnostics.CodeAnalysis.RequiresDynamicCodeAttribute("Row types are serialised by reflection; use the JsonTypeInfo overload for trimmed or AOT hosts.")]
                public static global::Graspea.Flint.Validation.ValidationResult Validate(global::Graspea.Flint.FlintBackend? backend = null) => Template.Validate(backend);
            }

            """.Replace("\r\n", "\n")));
    }

    // source: design §12.6.3 (mode B with JsonContext: the metadata from Default.GetTypeInfo(typeof(TRow)), cast, or an
    // InvalidOperationException naming the context and TRow; no trimming attributes; selectors over the bound members;
    // the generated part repeats the namespace and every containing type, accessibility omitted) and §12.6.2 (members get
    // the lesser accessibility, here internal)
    [Test]
    public void Write_ModeBWithContext_BindsTheUserTypeThroughTheMetadata()
    {
        var spec = Spec("""{"chart_spec":{"chartType":"Bar Chart","encodings":{"x":"region","y":"total","color":"class"}},"field_display_names":{"total":"Total"}}""");
        var target = new GeneratedTarget("App", ["partial class Reports<T>"], "SalesChart", "internal", "Charts/sales.flint.json", "1.0.0");
        var row = new BoundRowType("global::App.Sale", "App.Sale", new Dictionary<string, string> { ["region"] = "Region", ["total"] = "Total", ["class"] = "@class" }, "global::App.SalesJson", "App.SalesJson", Verbatim: false);

        var code = GeneratedChartWriter.Write(spec, target, row);

        Assert.That(code, Does.StartWith("""
            // <auto-generated/> Graspea.Flint.Generators 1.0.0 from Charts/sales.flint.json
            #nullable enable

            namespace App;

            partial class Reports<T>
            {
                static partial class SalesChart
                {
                    [global::System.Diagnostics.CodeAnalysis.ExperimentalAttribute("FLINTEXP001")]
                    private static global::Graspea.Flint.ChartTemplate<global::App.Sale>? __flint_template;

                    /// <summary>The chart of Charts/sales.flint.json without rows, built on first use; bind rows per call.</summary>
                    [global::System.Diagnostics.CodeAnalysis.ExperimentalAttribute("FLINTEXP001")]
                    internal static global::Graspea.Flint.ChartTemplate<global::App.Sale> Template
                    {
                        get => global::System.Threading.LazyInitializer.EnsureInitialized(ref __flint_template, static () =>
                            global::Graspea.Flint.Chart.Bar((global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<global::App.Sale>?)global::App.SalesJson.Default.GetTypeInfo(typeof(global::App.Sale))
                                ?? throw new global::System.InvalidOperationException("App.SalesJson has no metadata for App.Sale; add [JsonSerializable(typeof(App.Sale))] to it (FLINT106)."))
                                .X(r => r.Region)
                                .Y(r => r.Total)
                                .Color(r => r.@class)
                                .DisplayName(r => r.Total, "Total")
                                .ToTemplate());
                    }

                    /// <summary>A new document with <paramref name="rows"/> written to JSON now.</summary>
                    /// <param name="rows">The rows.</param>
                    /// <returns>The document.</returns>
                    [global::System.Diagnostics.CodeAnalysis.ExperimentalAttribute("FLINTEXP001")]
                    internal static global::Graspea.Flint.ChartAssemblyInput Build(global::System.Collections.Generic.IEnumerable<global::App.Sale> rows) => Template.Bind(rows);

            """.Replace("\r\n", "\n")));
        Assert.That(code, Does.Not.Contain("RequiresUnreferencedCode"));
        Assert.That(code, Does.EndWith("""
                    internal static global::Graspea.Flint.Validation.ValidationResult Validate(global::Graspea.Flint.FlintBackend? backend = null) => Template.Validate(backend);
                }
            }

            """.Replace("\r\n", "\n")));
    }

    // source: design §12.6.2 (FlintRowNaming.Verbatim on the reflection path: RowOptions without a naming policy) and
    // §12.6.3 (the trimming attributes without JsonContext); a chart type outside the catalog goes through Chart.Of, whose
    // builder binds channels with Encode (§12.4.1)
    [Test]
    public void Write_ModeBVerbatim_PassesRowOptionsWithoutANamingPolicy()
    {
        var spec = Spec("""{"chart_spec":{"chartType":"Image Chart","encodings":{"x":"Region"}}}""");
        var row = new BoundRowType("global::Sale", "Sale", new Dictionary<string, string> { ["Region"] = "Region" }, null, null, Verbatim: true);

        var code = GeneratedChartWriter.Write(spec, Charts with { Namespace = null }, row);

        Assert.That(code, Does.Contain("""
                        global::Graspea.Flint.Chart.Of<global::Sale>(new global::Graspea.Flint.ChartType("Image Chart"), new global::Graspea.Flint.RowOptions { PropertyNamingPolicy = null })
                            .Encode(global::Graspea.Flint.Channel.X, r => r.Region)
                            .ToTemplate());
            """.Replace("\r\n", "\n")));
        Assert.That(code, Does.Not.Contain("namespace"));
        Assert.That(code, Does.Contain("RequiresUnreferencedCodeAttribute"));
    }

    // source: design §12.6.3 (__flint_Json, the reserved name of the Extensions helper, emitted only when used)
    [Test]
    public void Write_UnknownEncodingKey_UsesTheReservedJsonHelper()
    {
        var spec = Spec("""{"chart_spec":{"chartType":"Bar Chart","encodings":{"x":{"field":"a","stack":true}}}}""");

        var code = GeneratedChartWriter.Write(spec, Charts, RowInference.Infer(spec, replay: false));

        Assert.That(code, Does.Contain("Extensions = new() { [\"stack\"] = __flint_Json(\"true\") }"));
        Assert.That(code, Does.Contain("private static global::System.Text.Json.JsonElement __flint_Json(string json)"));
    }

    // source: design §12.6.7 (an Error never stops generation; without a spec the members still exist, so the build fails
    // on the one diagnostic and not on a cascade of CS0117 errors in user code)
    [Test]
    public void WriteUnavailable_ModeA_DeclaresEveryMemberAndThrows()
    {
        var code = GeneratedChartWriter.WriteUnavailable(Charts, null, "The spec Charts/revenue.flint.json is not in AdditionalFiles (FLINT101).");

        Assert.That(code, Does.Contain("public sealed record Row();"));
        Assert.That(code, Does.Contain("public static global::Graspea.Flint.ChartTemplate<Row> Template => throw new global::System.InvalidOperationException(\"The spec Charts/revenue.flint.json is not in AdditionalFiles (FLINT101).\");"));
        foreach (var member in new[] { "Build(", "BuildAsync(", "WriteAsync(", "Validate(" })
        {
            Assert.That(code, Does.Contain(member));
        }
    }

    // source: design §12.6.3 (the output compiles in a user namespace that declares Chart, Row, SemanticType and Json types,
    // and inside a generic containing type) and §12.6.2 (the C# 12 floor); every corpus document in mode A, one compilation
    [Test]
    [Category("Contract")]
    public void Write_EveryCorpusDocument_CompilesInAHostileNamespace()
    {
        var sources = new List<(string, string)>
        {
            ("Hostile", "namespace Hostile { public class Chart { } public class Row { } public class SemanticType { } public class Json { } public class Graspea { } public partial class Outer<T> { } }"),
        };
        var cases = SpecCorpus.Accepted;
        for (var i = 0; i < cases.Count; i++)
        {
            var spec = Spec(cases[i].Json);
            var target = new GeneratedTarget("Hostile", ["partial class Outer<T>"], $"Case{i:D4}", "public", "case.flint.json", "0.0.0");
            sources.Add(($"Case{i:D4}", GeneratedChartWriter.Write(spec, target, RowInference.Infer(spec, replay: false))));
        }

        var compilation = Net8Compiler.Compile("Generated", sources)
            .WithOptions(GeneratorHarness.OptedIn);
        var problems = Net8Compiler.Problems(compilation);

        Assert.That(problems.Select(p => $"{p.Location.SourceTree?.FilePath}: {p}").Take(20), Is.Empty);
    }
}
