    private const string Revenue = """
        {
          "data": { "values": [ { "month": "2024-01-01", "revenue": 1200.50, "region": "EU" } ] },
          "semantic_types": { "month": "YearMonth", "revenue": "Amount" },
          "chart_spec": {
            "chartType": "Line Chart",
            "title": "Revenue by region",
            "encodings": { "x": "month", "y": { "field": "revenue" }, "color": { "field": "region" } },
            "baseSize": { "width": 800, "height": 400 },
            "chartProperties": { "interpolate": "monotone" }
          },
          "theme_spec": "economist"
        }
        """;

    internal static string Convert(string json, DataMode mode = DataMode.Inline, CodeStyle style = CodeStyle.Fluent, string? ns = null) =>
        SpecConverter.Convert(json, new ConversionOptions("RevenueChart") { Data = mode, Style = style, Namespace = ns, SourceName = "revenue.flint.json", Version = "0.5.1.1" }).Code;

    /// <summary>A minimal document around a chart_spec body and extra top-level members.</summary>
    internal static string Doc(string chartType, string encodings, string extra = "", string specExtra = "", string rows = "[{\"a\":\"x\",\"b\":1}]") =>
        $"{{\"data\":{{\"values\":{rows}}},{extra}\"chart_spec\":{{\"chartType\":\"{chartType}\",{specExtra}\"encodings\":{encodings}}}}}";

    internal static string[] Chain(string code)
    {
        var lines = code.Split('\n');
        var start = Array.FindIndex(lines, l => l.TrimStart().StartsWith("Chart.", StringComparison.Ordinal));
        return lines.Skip(start).TakeWhile(l => l.Length > 0 && !l.StartsWith('}')).Select(l => l.Trim()).ToArray();
    }

    // source: design §12.5.3, the example (fluent, inline) for revenue.flint.json; the design omits "using System;", which
    // DateOnly needs without implicit usings
    [Test]
    public void Convert_DesignExample_WritesTheExpectedClass()
    {
        Assert.That(Convert(Revenue, ns: "Charts"), Is.EqualTo("""
            // Generated by flint-cs 0.5.1.1 from revenue.flint.json; requires Graspea.Flint 0.5.1.1.
            #nullable enable
            using System;
            using System.Diagnostics.CodeAnalysis;
            using System.Text.Json.Serialization;
            using Graspea.Flint;

            namespace Charts;

            public static class RevenueChart
            {
                public sealed record Row(
                    [property: JsonPropertyName("month")] DateOnly Month,
                    [property: JsonPropertyName("revenue")] decimal Revenue,
                    [property: JsonPropertyName("region")] string Region);

                public static readonly Row[] Rows =
                [
                    new(new DateOnly(2024, 1, 1), 1200.50m, "EU"),
                ];

                [RequiresUnreferencedCode("Row types are serialised by reflection; use the JsonTypeInfo overload for trimmed or AOT hosts.")]
                [RequiresDynamicCode("Row types are serialised by reflection; use the JsonTypeInfo overload for trimmed or AOT hosts.")]
                public static ChartAssemblyInput Build() =>
                    Chart.Line(Rows)
                        .X(r => r.Month, SemanticType.YearMonth)
                        .Y(r => r.Revenue, SemanticType.Amount)
                        .Color(r => r.Region)
                        .Interpolate(LineChartInterpolate.Monotone)
                        .Title("Revenue by region")
                        .BaseSize(800, 400)
                        .Theme(ThemePreset.Economist)
                        .Build();
            }

            """.Replace("\r\n", "\n")));
    }

    // source: design §12.5.3 (determinism: the same input and options give byte-identical output)
