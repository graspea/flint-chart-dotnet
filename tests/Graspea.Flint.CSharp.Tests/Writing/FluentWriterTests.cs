    // source: design §12.4.1 ("other data keys, or values and url together" -> the data object keeps them in Extensions;
    // data.url -> ChartData.FromUrl)
    [Test]
    public void Convert_DataForms()
    {
        var url = Chain(Convert("{\"data\":{\"url\":\"https://example.com/r.json\"},\"chart_spec\":{\"chartType\":\"Bar Chart\",\"encodings\":{\"x\":\"a\"}}}"));
        Assert.That(url, Is.EqualTo(new[] { "Chart.Bar(ChartData.FromUrl(\"https://example.com/r.json\"))", ".X(\"a\")", ".Build();" }));

        var both = Chain(Convert(Doc("Bar Chart", "{\"x\":\"a\"}").Replace("\"data\":{\"values\":[{\"a\":\"x\",\"b\":1}]}", "\"data\":{\"values\":[{\"a\":\"x\",\"b\":1}],\"url\":\"u\"}")));
        Assert.That(both, Does.Contain(".Configure(d => (d.Data!.Extensions ??= new())[\"url\"] = Json(\"\\\"u\\\"\"))"));
    }

