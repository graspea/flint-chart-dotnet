    // source: design §12.5.2 (external: Build(JsonArray values), data.values written byte for byte to the sidecar, keys verbatim)
    [Test]
    public void Convert_External_WritesTheValuesBytesToTheSidecar()
    {
        var json = "{\"data\":{\"values\": [ {\"a\":\"x\", \"b\":1.50} ] },\"chart_spec\":{\"chartType\":\"Bar Chart\",\"encodings\":{\"x\":\"a\"}}}";
        var result = SpecConverter.Convert(json, new ConversionOptions("C") { Data = DataMode.External });

        Assert.That(result.Sidecar, Is.EqualTo("[ {\"a\":\"x\", \"b\":1.50} ]"));
        Assert.That(result.Code, Does.Contain("public static ChartAssemblyInput Build(JsonArray values) =>\n        Chart.Bar(ChartData.FromJson(values))\n            .X(\"a\")"));
    }

    // source: design §12.5.2 and §13.7 (parameter: Row, a template from the deferred entry, Build = Template.Bind,
    // BuildAsync = Template.BindAsync, WriteAsync = FlintJson.SerializeAsync(stream, Template.BindStream(rows), ct),
    // Validate = Template.Validate) and §12.6.3 (the template is built on first use with LazyInitializer in an annotated
    // getter)
    [Test]
    public void Convert_Parameter_WritesTheTemplateMembers()
    {
        var code = Convert(Revenue, DataMode.Parameter);

        Assert.That(code, Does.Contain("    private static ChartTemplate<Row>? template;\n"));
        Assert.That(code, Does.Contain("        get => LazyInitializer.EnsureInitialized(ref template, static () =>\n            Chart.Line<Row>()\n"));
        Assert.That(code, Does.Contain("                .ToTemplate());\n"));
        Assert.That(code, Does.Contain("public static ChartAssemblyInput Build(IEnumerable<Row> rows) => Template.Bind(rows);"));
        Assert.That(code, Does.Contain("public static ValueTask<ChartAssemblyInput> BuildAsync(IAsyncEnumerable<Row> rows, CancellationToken cancellationToken = default) =>\n        Template.BindAsync(rows, cancellationToken);"));
        Assert.That(code, Does.Contain("public static Task WriteAsync(Stream utf8Json, IAsyncEnumerable<Row> rows, CancellationToken cancellationToken = default) =>\n        FlintJson.SerializeAsync(utf8Json, Template.BindStream(rows), cancellationToken);"));
        Assert.That(code, Does.Contain("public static ValidationResult Validate(FlintBackend? backend = null) => Template.Validate(backend);"));
        Assert.That(code, Does.Not.Contain("Rows ="));
    }

    // source: design §12.5.2 (a data.url document emits ChartData.FromUrl in every mode)
    [Test]
    public void Convert_UrlInParameterMode_StaysAUrl()
    {
        var code = Convert("{\"data\":{\"url\":\"u\"},\"chart_spec\":{\"chartType\":\"Bar Chart\",\"encodings\":{\"x\":\"a\"}}}", DataMode.Parameter);

        Assert.That(Chain(code)[0], Is.EqualTo("Chart.Bar(ChartData.FromUrl(\"u\"))"));
        Assert.That(code, Does.Not.Contain("Template"));
    }

    // source: design §12.5.2 (the tool prints an Info above 1000 inline rows suggesting external) and §12.6.7 FLINT130
    // (a field without values and without a hint is a string)
    [Test]
    public void Convert_Notes()
    {
        var rows = "[" + string.Join(",", Enumerable.Repeat("{\"a\":1}", 1001)) + "]";
        var many = SpecConverter.Convert(Doc("Bar Chart", "{\"x\":\"a\"}", rows: rows), new ConversionOptions("C"));
        Assert.That(many.Notes, Is.EqualTo(new[] { "1001 rows are written inline; --data external keeps them in a sidecar file." }));

        var hints = SpecConverter.Convert("{\"chart_spec\":{\"chartType\":\"Bar Chart\",\"encodings\":{\"x\":\"a\"}}}", new ConversionOptions("C"));
        Assert.That(hints.Notes, Is.EqualTo(new[] { "The field \"a\" has no values and no type hint; its Row member is a string." }));
    }
