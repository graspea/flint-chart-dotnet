        Assert.That(Convert(Revenue), Is.EqualTo(Convert(Revenue)));
    }

    // source: design §12.4.1 ("chartType not in the catalog" -> Chart.Of(new ChartType("Image Chart"), …); a channel not on
    // the facade -> Encode(Channel.X, …) or Encode(new Channel("text"), …); any other key -> Property)
    [Test]
    public void Convert_UnknownChartType_UsesChartOf()
    {
        var chain = Chain(Convert(Doc("Image Chart", "{\"x\":\"a\",\"text\":\"b\"}", specExtra: "\"chartProperties\":{\"fit\":\"cover\"},")));

        Assert.That(chain, Is.EqualTo(new[] { "Chart.Of(new ChartType(\"Image Chart\"), Rows)", ".Encode(Channel.X, r => r.A)", ".Encode(new Channel(\"text\"), r => r.B)", ".Property(\"fit\", \"cover\")", ".Build();" }));
    }

    // source: design §12.4.1 (a channel the template's facade lacks -> Encode with the Channel constant)
    [Test]
    public void Convert_ChannelNotOnTheFacade_UsesEncode()
    {
        Assert.That(Chain(Convert(Doc("Bar Chart", "{\"strokeDash\":\"a\"}"))), Does.Contain(".Encode(Channel.StrokeDash, r => r.A)"));
    }

    // source: design §12.4.1 (an encoding object with more members -> new ChartEncoding { … } with constants; an unknown
    // literal -> new Aggregate("median"); an encoding without a field; unknown keys -> Extensions with the Json helper)
    [Test]
    public void Convert_EncodingObjects()
    {
        var chain = Chain(Convert(Doc("Bar Chart", "{\"x\":{\"field\":\"a\",\"type\":\"temporal\",\"sortOrder\":\"descending\",\"sortBy\":\"x\",\"scheme\":\"blues\",\"k\":1},\"y\":{\"field\":\"b\",\"aggregate\":\"median\"},\"color\":{\"aggregate\":\"count\"}}")));

        Assert.That(chain, Does.Contain(".X(new ChartEncoding { Field = \"a\", Type = EncodingType.Temporal, SortOrder = SortOrder.Descending, SortBy = \"x\", Scheme = \"blues\", Extensions = new() { [\"k\"] = Json(\"1\") } })"));
        Assert.That(chain, Does.Contain(".Y(new ChartEncoding { Field = \"b\", Aggregate = new Aggregate(\"median\") })"));
        Assert.That(chain, Does.Contain(".Color(new ChartEncoding { Aggregate = Aggregate.Count })"));
    }

    // source: design §12.4.1 (two or more plain, distinct fields on x or y -> Series with selectors; any other array ->
    // Encode(channel, EncodingValue.Series(…)); a one-entry array stays an array)
    [Test]
    public void Convert_Arrays()
    {
        var chain = Chain(Convert(Doc("Line Chart", "{\"x\":\"a\",\"y\":[\"a\",{\"field\":\"b\"}],\"color\":[\"a\",\"b\"],\"detail\":[\"a\"]}")));

        Assert.That(chain, Does.Contain(".Series(Channel.Y, r => r.A, r => r.B)"));
        Assert.That(chain, Does.Contain(".Encode(Channel.Color, EncodingValue.Series(new ChartEncoding { Field = \"a\" }, new ChartEncoding { Field = \"b\" }))"));
        Assert.That(chain, Does.Contain(".Encode(Channel.Detail, EncodingValue.Series(new ChartEncoding { Field = \"a\" }))"));
    }

    // source: design §12.4.1 (Series throws on duplicates, so a duplicate goes to the next row; a field the rows do not have
    // stays a string field name)
    [Test]
    public void Convert_SeriesWithADuplicateOrAMissingField()
    {
        Assert.That(Chain(Convert(Doc("Line Chart", "{\"y\":[\"a\",\"a\"]}"))), Does.Contain(".Encode(Channel.Y, EncodingValue.Series(new ChartEncoding { Field = \"a\" }, new ChartEncoding { Field = \"a\" }))"));
        Assert.That(Chain(Convert(Doc("Line Chart", "{\"y\":[\"a\",\"q\"]}"))), Does.Contain(".Series(Channel.Y, \"a\", \"q\")"));
    }

    // source: design §12.4.1 (encodings.ch = null -> Configure with null!; a property null -> Configure, because Property(k,
    // null) removes the key)
    [Test]
    public void Convert_Nulls_UseConfigure()
    {
        var chain = Chain(Convert(Doc("Bar Chart", "{\"x\":\"a\",\"color\":null}", specExtra: "\"chartProperties\":{\"k\":null},")));

        Assert.That(chain, Does.Contain(".Configure(d => d.ChartSpec.Encodings[\"color\"] = null!)"));
        Assert.That(chain, Does.Contain(".Configure(d => (d.ChartSpec.ChartProperties ??= new())[\"k\"] = null)"));
    }

    // source: design §12.4.1 (binary -> bool method; discrete value equal to an enum member's written value -> the member;
    // a label, an array or a value outside the option set -> Property; continuous -> the method; JsonNode-mapped -> the
    // method; any other key by JSON kind -> Property, an array or object through JsonNode.Parse)
    [Test]
    public void Convert_ChartProperties()
    {
        var line = Chain(Convert(Doc("Line Chart", "{\"x\":\"a\"}", specExtra: "\"chartProperties\":{\"showPoints\":true,\"interpolate\":\"step-after\",\"xAxisType\":\"zzz\",\"other\":12.5,\"list\":[1,2]},")));
        Assert.That(line, Is.SupersetOf(new[] { ".ShowPoints(true)", ".Interpolate(LineChartInterpolate.StepAfter)", ".Property(\"xAxisType\", \"zzz\")", ".Property(\"other\", 12.5)", ".Property(\"list\", JsonNode.Parse(\"\"\"[1,2]\"\"\"))" }));

        var map = Chain(Convert(Doc("Map", "{\"longitude\":\"a\"}", specExtra: "\"chartProperties\":{\"projectionCenter\":[10,50]},")));
        Assert.That(map, Does.Contain(".Property(\"projectionCenter\", JsonNode.Parse(\"\"\"[10,50]\"\"\"))"));

        var label = Chain(Convert(Doc("Map", "{\"longitude\":\"a\"}", specExtra: "\"chartProperties\":{\"projectionCenter\":\"Europe [10, 50]\"},")));
        Assert.That(label, Does.Contain(".ProjectionCenter(MapProjectionCenter.Europe)"));

        var bar = Chain(Convert(Doc("Bar Chart", "{\"x\":\"a\"}", specExtra: "\"chartProperties\":{\"cornerRadius\":4},")));
        Assert.That(bar, Does.Contain(".CornerRadius(4)"));

        var radar = Chain(Convert(Doc("Radar Chart", "{\"x\":\"a\"}", specExtra: "\"chartProperties\":{\"filled\":true},")));
        Assert.That(radar, Does.Contain(".Filled(true)"));
    }

    // source: design §12.4.1 (a trivial annotation on a field a channel call binds is folded into the first such call;
    // other annotations -> Annotate, with a selector when the rows have the field; unregistered -> new SemanticType;
    // Name -> SemanticType.NameType; an annotation object -> new SemanticAnnotation { … })
    [Test]
    public void Convert_Annotations()
    {
        var chain = Chain(Convert(Doc("Bar Chart", "{\"x\":\"a\",\"y\":\"a\"}", extra: "\"semantic_types\":{\"a\":\"Category\",\"b\":{\"semanticType\":\"Amount\",\"unit\":\"USD\",\"intrinsicDomain\":[0,100]},\"c\":\"Name\",\"d\":\"Revenue\"},")));

        Assert.That(chain, Is.EqualTo(new[]
        {
            "Chart.Bar(Rows)",
            ".X(r => r.A, SemanticType.Category)",
            ".Y(r => r.A)",
            ".Annotate(r => r.B, new SemanticAnnotation { Type = SemanticType.Amount, Unit = \"USD\", IntrinsicDomain = [0, 100] })",
            ".Annotate(\"c\", SemanticType.NameType)",
            ".Annotate(\"d\", new SemanticType(\"Revenue\"))",
            ".Build();",
        }));
    }

    // source: design §12.4.1 (field_display_names -> DisplayName with a selector or the field name; theme preset; unknown
    // preset -> new ThemePreset; options -> Options(o => { … }) with undeclared keys in o.Extensions; unknown top-level keys
    // -> Configure into Extensions)
    [Test]
    public void Convert_DisplayNamesThemeOptionsExtensions()
    {
        var chain = Chain(Convert(Doc("Bar Chart", "{\"x\":\"a\"}", extra: "\"field_display_names\":{\"a\":\"Alpha\",\"z\":\"Zed\"},\"theme_spec\":\"no-such\",\"options\":{\"maxStretch\":1.5,\"continuousMarkCrossSection\":{\"x\":1,\"y\":2,\"seriesCountAxis\":\"auto\"},\"background\":\"#fff\"},\"interaction_spec\":{\"zoom\":true},")));

