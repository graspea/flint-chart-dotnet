    // source: design §12.6.2 (the attributes: internal, [Embedded], [Conditional("FLINT_GENERATOR_ATTRIBUTES")],
    // [Experimental("FLINTEXP001")] on both attribute classes and FlintRowNaming; FlintChartAttribute(string path) with Path, the generic
    // FlintChartAttribute<TRow> with RowNaming and JsonContext; FlintRowNaming CamelCase = 0, Verbatim = 1), a public
    // contract (§12.8) pinned here as text
    [Test]
    public void Initialize_AddsTheAttributesAndTheEmbeddedAttribute()
    {
        var run = GeneratorHarness.Run("class Empty { }");

        var hints = run.Result.Results[0].GeneratedSources.Select(s => s.HintName).ToList();
        Assert.That(hints, Does.Contain("Graspea.Flint.FlintChartAttribute.g.cs"));
        Assert.That(run.Output.GetTypeByMetadataName("Microsoft.CodeAnalysis.EmbeddedAttribute"), Is.Not.Null);
        Assert.That(run.Source("Graspea.Flint.FlintChartAttribute.g.cs"), Is.EqualTo("""
            // <auto-generated/> Graspea.Flint.Generators
            #nullable enable

            namespace Graspea.Flint
            {
                /// <summary>
                /// Generates a typed chart builder from a Flint ChartAssemblyInput JSON file in the project (mode A): a nested
                /// <c>Row</c> record inferred from the spec, <c>Template</c>, <c>Build</c>, <c>BuildAsync</c>, <c>WriteAsync</c> and
                /// <c>Validate</c>. Apply it to a <c>static partial class</c>.
                /// </summary>
                [global::System.AttributeUsage(global::System.AttributeTargets.Class, AllowMultiple = false, Inherited = false)]
                [global::System.Diagnostics.Conditional("FLINT_GENERATOR_ATTRIBUTES")]
                [global::System.Diagnostics.CodeAnalysis.Experimental("FLINTEXP001")]
                [global::Microsoft.CodeAnalysis.Embedded]
                internal sealed class FlintChartAttribute : global::System.Attribute
                {
                    /// <summary>Generates the builder of the spec at <paramref name="path"/>.</summary>
                    /// <param name="path">The spec, relative to the project directory, with <c>/</c> or <c>\</c>.</param>
                    public FlintChartAttribute(string path)
                    {
                        Path = path;
                    }

                    /// <summary>The spec, relative to the project directory.</summary>
                    public string Path { get; }
                }

                /// <summary>
                /// Generates a typed chart builder from a Flint ChartAssemblyInput JSON file in the project over an existing row
                /// type (mode B): every field of the spec binds to a member of <typeparamref name="TRow"/>, and the build reports a
                /// field without a member or of an incompatible type. Apply it to a <c>static partial class</c>.
                /// </summary>
                /// <typeparam name="TRow">The row type.</typeparam>
                [global::System.AttributeUsage(global::System.AttributeTargets.Class, AllowMultiple = false, Inherited = false)]
                [global::System.Diagnostics.Conditional("FLINT_GENERATOR_ATTRIBUTES")]
                [global::System.Diagnostics.CodeAnalysis.Experimental("FLINTEXP001")]
                [global::Microsoft.CodeAnalysis.Embedded]
                internal sealed class FlintChartAttribute<TRow> : global::System.Attribute
                {
                    /// <summary>Generates the builder of the spec at <paramref name="path"/>.</summary>
                    /// <param name="path">The spec, relative to the project directory, with <c>/</c> or <c>\</c>.</param>
                    public FlintChartAttribute(string path)
                    {
                        Path = path;
                    }

                    /// <summary>The spec, relative to the project directory.</summary>
                    public string Path { get; }

                    /// <summary>How the reflection row path names keys: camelCase (the default, as <c>RowOptions.Default</c>) or
                    /// the member names verbatim. Leave it unset with <see cref="JsonContext"/>, whose options decide.</summary>
                    public FlintRowNaming RowNaming { get; set; }

                    /// <summary>A <c>JsonSerializerContext</c> with metadata for <typeparamref name="TRow"/>: rows are then written
                    /// through it, which is trimming- and AOT-safe.</summary>
                    public global::System.Type? JsonContext { get; set; }
                }

                /// <summary>How the reflection row path of <see cref="FlintChartAttribute{TRow}"/> names keys.</summary>
                [global::System.Diagnostics.CodeAnalysis.Experimental("FLINTEXP001")]
                [global::Microsoft.CodeAnalysis.Embedded]
                internal enum FlintRowNaming
                {
                    /// <summary>camelCase keys (<c>FiscalYear</c> is written as <c>fiscalYear</c>), as <c>RowOptions.Default</c>.</summary>
                    CamelCase = 0,

                    /// <summary>The member names as written.</summary>
                    Verbatim = 1,
                }
            }

            """.Replace("\r\n", "\n")));
        Assert.That(run.Problems(), Is.Empty);
    }

    // source: design D7.11 (the attribute surface, FlintRowNaming included, carries FLINTEXP001): a project that has not
    // opted in compiles the added attributes cleanly and gets FLINTEXP001 where it names FlintRowNaming
    [Test]
    public void FlintRowNaming_OutsideTheAttribute_NeedsTheOptIn()
    {
        Assert.That(GeneratorHarness.Run(["class Empty { }"], [], options: Net8Compiler.Options).Problems(), Is.Empty);

        var run = GeneratorHarness.Run(["static class Names { public const Graspea.Flint.FlintRowNaming Naming = Graspea.Flint.FlintRowNaming.Verbatim; }"], [], options: Net8Compiler.Options);
        Assert.That(run.Problems().Select(p => p.Id), Has.Some.EqualTo("FLINTEXP001"));
    }

    // source: design §12.6.2 ([Conditional] keeps the attributes out of the compiled metadata, so nothing reaches run time)
    [Test]
    public void Attributes_AreNotEmittedIntoMetadata()
    {
        var run = GeneratorHarness.Run("namespace App; [Graspea.Flint.FlintChart(\"sales.flint.json\")] public static partial class SalesChart;", ("sales.flint.json", Sales));
        var (assembly, context) = Net8Compiler.Load((CSharpCompilation)run.Output);
        try
        {
            Assert.That(assembly.GetType("App.SalesChart")!.GetCustomAttributesData().Select(a => a.AttributeType.Name), Does.Not.Contain("FlintChartAttribute"));
        }
        finally
        {
            context.Unload();
        }
    }

    /// <summary>The generator's version as its header writes it: the informational version without build metadata.</summary>
    private static string GeneratorVersion =>
        typeof(Graspea.Flint.Generators.FlintChartGenerator).Assembly.GetCustomAttributes(typeof(System.Reflection.AssemblyInformationalVersionAttribute), false)
            .Cast<System.Reflection.AssemblyInformationalVersionAttribute>().Single().InformationalVersion.Split('+')[0];

    // source: design §12.6.3 (one file per target, hint <Namespace>.<Containing>.<Class>.flint.g.cs, headed
    // "// <auto-generated/> Graspea.Flint.Generators <version> from <project-relative path>", the mode A members, no using
    // directive, every type global::-qualified, reserved __flint_ names) and §12.4.3 (the Row of the spec: month is a
    // date, revenue a double)
    [Test]
    public void ModeA_GeneratesTheRowAndTheTemplateMembers()
    {
        var run = GeneratorHarness.Run("namespace App;\n[Graspea.Flint.FlintChart(\"Charts/sales.flint.json\")]\npublic static partial class SalesChart;", ("Charts/sales.flint.json", Sales));

        const string reflection = "\"Row types are serialised by reflection; use the JsonTypeInfo overload for trimmed or AOT hosts.\"";
        Assert.That(run.Source("App.SalesChart.flint.g.cs").Replace(GeneratorVersion, "<version>", StringComparison.Ordinal), Is.EqualTo($$"""
            // <auto-generated/> Graspea.Flint.Generators <version> from Charts/sales.flint.json
            #nullable enable

            namespace App;

            static partial class SalesChart
            {
                /// <summary>A row of the chart, inferred from Charts/sales.flint.json.</summary>
                /// <param name="Month">The <c>month</c> field.</param>
                /// <param name="Revenue">The <c>revenue</c> field.</param>
                [global::System.Diagnostics.CodeAnalysis.ExperimentalAttribute("FLINTEXP001")]
                public sealed record Row(
                    [property: global::System.Text.Json.Serialization.JsonPropertyNameAttribute("month")] global::System.DateOnly Month,
                    [property: global::System.Text.Json.Serialization.JsonPropertyNameAttribute("revenue")] double Revenue);

                [global::System.Diagnostics.CodeAnalysis.ExperimentalAttribute("FLINTEXP001")]
                private static global::Graspea.Flint.ChartTemplate<Row>? __flint_template;

                /// <summary>The chart of Charts/sales.flint.json without rows, built on first use; bind rows per call.</summary>
                [global::System.Diagnostics.CodeAnalysis.ExperimentalAttribute("FLINTEXP001")]
                public static global::Graspea.Flint.ChartTemplate<Row> Template
                {
                    [global::System.Diagnostics.CodeAnalysis.RequiresUnreferencedCodeAttribute({{reflection}})]
                    [global::System.Diagnostics.CodeAnalysis.RequiresDynamicCodeAttribute({{reflection}})]
                    get => global::System.Threading.LazyInitializer.EnsureInitialized(ref __flint_template, static () =>
                        global::Graspea.Flint.Chart.Bar<Row>()
                            .X(r => r.Month)
                            .Y(r => r.Revenue)
                            .ToTemplate());
                }

                /// <summary>A new document with <paramref name="rows"/> written to JSON now.</summary>
                /// <param name="rows">The rows.</param>
                /// <returns>The document.</returns>
                [global::System.Diagnostics.CodeAnalysis.ExperimentalAttribute("FLINTEXP001")]
                [global::System.Diagnostics.CodeAnalysis.RequiresUnreferencedCodeAttribute({{reflection}})]
                [global::System.Diagnostics.CodeAnalysis.RequiresDynamicCodeAttribute({{reflection}})]
                public static global::Graspea.Flint.ChartAssemblyInput Build(global::System.Collections.Generic.IEnumerable<Row> rows) => Template.Bind(rows);

                /// <summary>A new document with the rows of an asynchronous source written to JSON.</summary>
                /// <param name="rows">The rows; end a database query with <c>.AsAsyncEnumerable()</c>.</param>
                /// <param name="cancellationToken">Passed to the source and checked before each row.</param>
                /// <returns>The document.</returns>
                [global::System.Diagnostics.CodeAnalysis.ExperimentalAttribute("FLINTEXP001")]
                [global::System.Diagnostics.CodeAnalysis.RequiresUnreferencedCodeAttribute({{reflection}})]
                [global::System.Diagnostics.CodeAnalysis.RequiresDynamicCodeAttribute({{reflection}})]
                public static global::System.Threading.Tasks.ValueTask<global::Graspea.Flint.ChartAssemblyInput> BuildAsync(global::System.Collections.Generic.IAsyncEnumerable<Row> rows, global::System.Threading.CancellationToken cancellationToken = default) =>
                    Template.BindAsync(rows, cancellationToken);

                /// <summary>Writes the document to <paramref name="utf8Json"/> with the rows streamed from their source.</summary>
                /// <param name="utf8Json">The stream.</param>
                /// <param name="rows">The rows.</param>
                /// <param name="cancellationToken">Passed to the source and to every write.</param>
                /// <returns>The write.</returns>
                [global::System.Diagnostics.CodeAnalysis.ExperimentalAttribute("FLINTEXP001")]
                [global::System.Diagnostics.CodeAnalysis.RequiresUnreferencedCodeAttribute({{reflection}})]
                [global::System.Diagnostics.CodeAnalysis.RequiresDynamicCodeAttribute({{reflection}})]
                public static global::System.Threading.Tasks.Task WriteAsync(global::System.IO.Stream utf8Json, global::System.Collections.Generic.IAsyncEnumerable<Row> rows, global::System.Threading.CancellationToken cancellationToken = default) =>
                    global::Graspea.Flint.Serialization.FlintJson.SerializeAsync(utf8Json, Template.BindStream(rows), cancellationToken);

                /// <summary>Validates the spec and the row metadata without rows.</summary>
                /// <param name="backend">The target backend; null means every backend that has the template.</param>
                /// <returns>The issues.</returns>
                [global::System.Diagnostics.CodeAnalysis.ExperimentalAttribute("FLINTEXP001")]
                [global::System.Diagnostics.CodeAnalysis.RequiresUnreferencedCodeAttribute({{reflection}})]
                [global::System.Diagnostics.CodeAnalysis.RequiresDynamicCodeAttribute({{reflection}})]
                public static global::Graspea.Flint.Validation.ValidationResult Validate(global::Graspea.Flint.FlintBackend? backend = null) => Template.Validate(backend);
            }

            """.Replace("\r\n", "\n")));
        Assert.That(run.Diagnostics, Is.Empty);
        Assert.That(run.Problems(), Is.Empty);
    }

    // source: design §12.6.2 and D7.11 (the attributes and every generated member carry [Experimental("FLINTEXP001")]; a
    // user opts in once with NoWarn): without the opt-in, the only diagnostics are FLINTEXP001 in the user's code, never in
    // the generated file
    [Test]
    public void ModeA_WithoutTheOptIn_ReportsFlintexp001OnlyInUserCode()
    {
        var source = "namespace App;\n[Graspea.Flint.FlintChart(\"sales.flint.json\")]\npublic static partial class SalesChart;\n"
            + "public static class Use { public static object M() => SalesChart.Validate(); }";
        var run = GeneratorHarness.Run([source], [("sales.flint.json", Sales)], options: Net8Compiler.Options);

        var problems = run.Problems();
        Assert.That(problems.Select(p => p.Id).Distinct(), Is.EqualTo(new[] { "FLINTEXP001" }));
        Assert.That(problems.Select(p => p.Location.SourceTree!.FilePath).Distinct(), Is.EqualTo(new[] { "/repo/app/Source0.cs" }));
        Assert.That(problems, Has.Length.EqualTo(2), "the attribute and the call");
    }

