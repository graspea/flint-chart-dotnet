    // source: design §12.6.3 (mode B with JsonContext: metadata from the context, no trimming attributes, selectors over the
    // bound members, the annotation folded into the channel call of §12.4.1) and §12.6.5 (rule 1 [JsonPropertyName], then
    // the context's camelCase from JsonSerializerDefaults.Web);
    // System.Text.Json's own source generator runs beside it, as in a real build
    [Test]
    public void ModeB_WithContext_BindsTheMembersAndCompiles()
    {
        var source = Sale + "\n[Graspea.Flint.FlintChart<Sale>(\"sale.flint.json\", JsonContext = typeof(SalesJson))]\npublic static partial class SaleChart;";
        var compilation = GeneratorHarness.Compilation([source]);
        var driver = CSharpGeneratorDriver.Create(
            [new Graspea.Flint.Generators.FlintChartGenerator().AsSourceGenerator(), Net8Compiler.JsonSourceGenerator()],
            [new MemoryText(GeneratorHarness.ProjectDirectory + "sale.flint.json", SaleSpec)],
            new CSharpParseOptions(LanguageVersion.CSharp12),
            new GlobalOptionsProvider(new Dictionary<string, string> { ["build_property.ProjectDir"] = GeneratorHarness.ProjectDirectory }));
        var run = GeneratorHarness.Rerun(driver, compilation);

        var code = run.Source("App.SaleChart.flint.g.cs");
        Assert.That(code, Does.Contain("global::Graspea.Flint.Chart.Bar((global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<global::App.Sale>?)global::App.SalesJson.Default.GetTypeInfo(typeof(global::App.Sale))"));
        Assert.That(code, Does.Contain(".X(r => r.Month)"));
        Assert.That(code, Does.Contain(".Y(r => r.Revenue)"));
        Assert.That(code, Does.Contain(".Color(r => r.Region, global::Graspea.Flint.SemanticType.Region)"));
        Assert.That(code, Does.Not.Contain("RequiresUnreferencedCode"));
        Assert.That(run.Diagnostics.Where(d => d.Id.StartsWith("FLINT", StringComparison.Ordinal)), Is.Empty);
        Assert.That(run.Problems(), Is.Empty);
    }

    // source: design §12.6.3 (a public class bound to an internal TRow gets internal members, instead of CS0050/CS0051 in
    // generated code)
    [Test]
    public void ModeB_PublicClassOverInternalRow_GetsInternalMembers()
    {
        var source = "namespace App;\ninternal sealed record Sale(string Month, double Revenue);\n[Graspea.Flint.FlintChart<Sale>(\"sales.flint.json\")]\npublic static partial class SaleChart;";
        var run = GeneratorHarness.Run(source, ("sales.flint.json", Sales));

        var code = run.Source("App.SaleChart.flint.g.cs");
