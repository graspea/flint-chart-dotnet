        Assert.That(code, Does.Not.Contain("public static"));
        Assert.That(run.Problems(), Is.Empty);
    }

    // source: design §12.6.3 (name binding: the output compiles in a user namespace that declares Chart, Row, SemanticType
    // and Json types, and inside a generic containing type; the hint name replaces characters outside [A-Za-z0-9_.])
    [Test]
    public void ModeA_InAHostileNamespaceAndAGenericContainingType_Compiles()
    {
        var source = """
            namespace Charts
            {
                public class Chart { }
                public class Row { }
                public class SemanticType { }
                public class Json { }
                public class Graspea { }
                public partial class Outer<T>
                {
                    [global::Graspea.Flint.FlintChart("sales.flint.json")]
                    internal static partial class SalesChart;
                }
            }
            """;
        var annotated = Sales.Replace("\"chart_spec\"", "\"semantic_types\": { \"revenue\": \"Amount\" }, \"theme_spec\": \"economist\", \"chart_spec\"", StringComparison.Ordinal)
            .Replace("\"y\": \"revenue\"", "\"y\": { \"field\": \"revenue\", \"stack\": true }", StringComparison.Ordinal);
        var run = GeneratorHarness.Run(source, ("sales.flint.json", annotated));

        Assert.That(run.Result.Results[0].GeneratedSources.Select(s => s.HintName), Does.Contain("Charts.Outer_1.SalesChart.flint.g.cs"));
        Assert.That(run.Source("Charts.Outer_1.SalesChart.flint.g.cs"), Does.Contain("partial class Outer<T>\n{\n    static partial class SalesChart"));
        Assert.That(run.Problems(), Is.Empty);
    }

    // source: design §12.6.4 (paths resolve against the project directory) and the macOS build, where MSBuild reports the
    // project directory as /var/... and the compiler the same file as /private/var/... (found by
    // scripts/check-generator-flow.sh in a temporary folder)
    [Test]
    public void Spec_UnderAResolvedRootLink_StillMatches()
    {
        var compilation = GeneratorHarness.Compilation(["[Graspea.Flint.FlintChart(\"sales.flint.json\")] public static partial class SalesChart;"]);
        var driver = GeneratorHarness.Driver([new MemoryText("/private/var/app/sales.flint.json", Sales)], projectDirectory: "/var/app/");

        var run = GeneratorHarness.Rerun(driver, compilation);

        Assert.That(run.Diagnostics, Is.Empty);
        Assert.That(run.Source("SalesChart.flint.g.cs"), Does.Contain("Chart.Bar<Row>()"));
    }

    // source: design §12.6.4 (MSBuild keeps duplicate AdditionalFiles items; the matcher deduplicates by normalised path,
    // the first wins): a spec listed twice yields one source and each finding once
    [Test]
    public void DuplicatedAdditionalText_YieldsOneSpec()
    {
        var spec = Sales.Replace("\"Bar Chart\"", "\"Image Chart\"", StringComparison.Ordinal);
        var run = GeneratorHarness.Run("[Graspea.Flint.FlintChart(\"sales.flint.json\")] public static partial class SalesChart;", ("sales.flint.json", spec), ("./sales.flint.json", spec));

        Assert.That(run.Diagnostics.Select(d => d.Id), Is.EqualTo(new[] { "FLINT110" }));
        Assert.That(run.Result.Results[0].GeneratedSources.Count(s => s.HintName.EndsWith(".flint.g.cs", StringComparison.Ordinal)), Is.EqualTo(1));
    }
